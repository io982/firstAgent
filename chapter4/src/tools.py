"""
Инструменты Главы 4 — в том же реестре @tool, что и всё остальное.

Второго реестра по-прежнему нет: поиск по документам появляется у агента
ровно так же, как в Главе 2 появился калькулятор, а в Главе 3 — память.

Обратите внимание на форму ответов. Инструмент, который ничего не нашёл,
не молчит и не возвращает пустую строку: он говорит «не нашёл» и прямым
текстом запрещает выдумывать. Без этой строчки маленькая модель, получив
пустой результат, охотно отвечает по памяти обучения — и внешне это
неотличимо от настоящего ответа по документам.
"""

import os
import sys

sys.path.append(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

from chapter2.src.tools import tool

from .embeddings import EmbeddingError
from .knowledge import get_knowledge_base
from .semantic_memory import get_semantic_memory

# ====================================================================
# БЮДЖЕТ ВЫДАЧИ
# ====================================================================

# Сколько токенов найденного текста инструмент имеет право вернуть.
# Значение по умолчанию — заглушка: настоящее считает агент, потому что
# известно оно только после сборки системного промпта (см. agent.py).
# Модуль не может импортировать агента — агент импортирует модуль.
DEFAULT_RETRIEVAL_BUDGET = 500

_retrieval_budget = DEFAULT_RETRIEVAL_BUDGET


def set_retrieval_budget(tokens: int) -> None:
    """Ставит потолок на объём выдачи поиска (зовётся из agent.py)."""
    global _retrieval_budget
    _retrieval_budget = max(100, int(tokens))


def get_retrieval_budget() -> int:
    return _retrieval_budget


# ====================================================================
# ИНСТРУМЕНТЫ
# ====================================================================

@tool
def search_docs(query: str) -> str:
    """Ищет ответ в базе знаний проекта по смыслу вопроса.

    Вызывай ВСЕГДА, когда вопрос про этот проект, его настройки, ограничения
    или документацию — даже если кажется, что ответ известен.

    Args:
        query: Вопрос своими словами, а не ключевое слово
    """
    if not query or not query.strip():
        return "Ошибка: пустой запрос. Передай в query вопрос целиком."

    try:
        context = get_knowledge_base().retrieve(query, budget_tokens=get_retrieval_budget())
    except EmbeddingError as e:
        return (
            f"Ошибка поиска: {e}. Скажи пользователю, что база знаний недоступна, "
            f"и не отвечай по памяти."
        )

    if not context:
        return (
            f"❌ В базе знаний ничего не найдено по запросу «{query}». "
            f"Так и скажи пользователю: в документах этого нет. НЕ ВЫДУМЫВАЙ ответ."
        )

    return (
        "📄 Самые похожие фрагменты из базы знаний. Это КАНДИДАТЫ, а не готовый "
        "ответ: поиск возвращает их всегда, даже когда ответа в базе нет. "
        "Если ответа на вопрос в них нет — скажи «в документах этого нет». "
        f"Если есть — отвечай только по ним и назови источник.\n\n{context}"
    )


@tool
def recall_like(query: str) -> str:
    """Ищет факт в долгосрочной памяти по смыслу, а не по точному ключу.

    Вызывай, когда точный ключ неизвестен: «что я говорил про сервер»,
    «как меня зовут». Если ключ известен точно — быстрее обычный recall.

    Args:
        query: Что нужно вспомнить, своими словами
    """
    if not query or not query.strip():
        return "Ошибка: пустой запрос. Передай в query то, что нужно вспомнить."

    try:
        return get_semantic_memory().recall_like(query)
    except EmbeddingError as e:
        return (
            f"Ошибка поиска по памяти: {e}. Попробуй обычный recall по точному ключу "
            f"или скажи пользователю, что не можешь вспомнить."
        )
