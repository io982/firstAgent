"""
Токенизация под лексический поиск: из текста в слова, по которым ищут (пункт 6.1).

Векторный поиск Глав 4 и 5 сравнивает СМЫСЛ и потому слеп к точному
совпадению: `is_safe_query` не находится вопросом, в котором нет слова
`is_safe_query`. Лексический поиск устроен наоборот — он не знает про смысл
вовсе и сравнивает слова. Значит первое, что нужно решить: что считать
словом в исходнике.

Обычная текстовая токенизация здесь не годится, и видно это на одном имени:

    обычная      is_safe_query  →  is_safe_query
    наша         is_safe_query  →  is_safe_query, safe, query

Первая строка находит функцию только по точному имени целиком. Вторая
находит её ещё и вопросом «безопасность query» — потому что имя разобрано
на слова так же, как в карточке фрагмента Главы 5 (см. cards.split_identifier).
Целое имя при этом остаётся токеном и весит больше всех: оно встречается
в считанных фрагментах, а `query` — в сотнях.

Два решения, которые стоит проговорить.

**Пунктуация выброшена.** Черновик главы хранил `(`, `)`, `:`, `=` как
отдельные токены. Скобка есть почти в каждом фрагменте кода, её IDF близок
к нулю, и на ранжирование она не влияет — зато занимает половину индекса.
Проверка на это есть в тестах: токен, встречающийся во всех документах,
получает вес около нуля.

**Служебные слова выброшены — и русские тоже.** Дело не в размере индекса,
а в том, что на этом держится порог «в коде этого нет» (пункт 6.4). Докстроки
и комментарии в этом проекте написаны по-русски, поэтому вопрос «как
приготовить борщ» без вычистки служебных слов совпал бы с половиной
корпуса по слову «как» — и ноль перестал бы быть нулём.
"""

import re

from chapter5.src.cards import split_identifier

# Токены короче двух символов выбрасываются: `i`, `n`, `x` есть в каждом
# втором фрагменте и не помогают найти ничего.
MIN_TOKEN_LEN = 2

# Ключевые слова языков и служебные имена. Каждое встречается почти
# в каждом фрагменте, то есть весит около нуля и только раздувает индекс.
CODE_STOP_TOKENS = frozenset({
    "def", "class", "return", "import", "from", "as", "pass", "raise", "try",
    "except", "finally", "with", "yield", "lambda", "global", "nonlocal",
    "if", "elif", "else", "for", "while", "break", "continue", "and", "or",
    "not", "in", "is", "none", "true", "false", "self", "cls", "args",
    "kwargs", "init", "main", "print", "str", "int", "float", "bool", "list",
    "dict", "set", "tuple", "type", "function", "const", "let", "var",
    "export", "default", "new", "this", "await", "async",
})

# Служебные слова русского вопроса. Без них порог из пункта 6.4 не работает:
# «как», «где» и «что» есть в комментариях всего проекта.
RU_STOP_TOKENS = frozenset({
    "и", "в", "на", "не", "что", "как", "где", "это", "для", "по", "из",
    "но", "то", "же", "бы", "или", "все", "всё", "есть", "быть", "он", "она",
    "они", "мы", "вы", "я", "ты", "его", "её", "их", "при", "до", "за", "от",
    "об", "про", "так", "уже", "ещё", "еще", "если", "чтобы", "когда", "кто",
    "чем", "нет", "да", "был", "была", "было", "были", "тут", "там", "здесь",
    "можно", "нужно", "надо", "какой", "какая", "какие", "который", "которая",
})

STOP_TOKENS = CODE_STOP_TOKENS | RU_STOP_TOKENS

# Слова, которыми задают вопрос О КОДЕ. Они описывают ФОРМУ вопроса,
# а не его предмет: «где реализован класс X» — про X, а не про то, что
# в проекте есть слово «класс».
#
# Из индекса они не выбрасываются — по ним ищут, и «реализация» в докстроке
# полезна. Они не считаются только в одном месте: когда решается, есть ли
# в проекте ответ (см. hybrid.lexical_signal).
#
# Без этого списка отказ «в проекте этого нет» не срабатывает НИКОГДА.
# Маршрутизация Главы 5 отправляет вопрос в поиск по коду как раз тогда,
# когда в нём есть слова «где», «реализован», «функция», «класс», — и все
# они в корпусе, разумеется, встречаются. Живая проверка: вопрос вида
# «где реализован класс X» с выдуманным именем X показывал 40% найденных
# слов и проходил как вопрос, ответ на который где-то есть, — хотя из всего
# вопроса в проекте нашлись ровно «где», «реализован» и «класс».
#
# Имя X здесь намеренно не написано буквой алфавита, а оставлено буквой X:
# любой конкретный пример, записанный в этот комментарий, попадёт в индекс
# и перестанет быть примером отсутствующего слова. Проверено на себе.
#
# Списка «файл», «файлы», «файлов» тут НЕТ, и это не забывчивость. В вопросе
# «где реализовано чтение файлов» файлы — предмет, а не форма: выбросив их,
# мы оставляем одно слово «чтение», которого в коде нет (там «читает»
# и «чтения»), получаем ноль найденных слов и отказ на совершенно
# нормальном вопросе. Живой прогон на этом и споткнулся. «Класс», «метод»
# и «функция» предметом почти не бывают, а «файл» — сплошь и рядом.
QUESTION_FRAME_TOKENS = frozenset({
    "реализован", "реализована", "реализовано", "реализованы", "реализация",
    "определён", "определен", "определена", "определено", "определяется",
    "находится", "находятся", "лежит", "лежат", "написан", "написана",
    "используется", "вызывается", "работает", "устроен", "устроена", "устроено",
    "код", "кода", "коде", "кодом",
    "проект", "проекта", "проекте", "проектом",
    "модуль", "модуля", "модуле",
    "функция", "функции", "функцию", "функций",
    "класс", "класса", "классе", "классов",
    "метод", "метода", "методе", "методов",
    "переменная", "переменной", "константа", "константы",
    "агент", "агента", "агенте",
})

# Что считается словом: буквы (латиница и кириллица), цифры и подчёркивание.
# Подчёркивание внутри — обязательно, иначе `is_safe_query` распадётся ещё
# до того, как мы решим, разбирать его или нет.
_WORD = re.compile(r"[^\W\d_][\w]*", re.UNICODE)

# Числа отдельно: номер ошибки и версия — это то, что ищут точным совпадением.
_NUMBER = re.compile(r"\d[\w.]*")

_TOKEN = re.compile(f"{_WORD.pattern}|{_NUMBER.pattern}", re.UNICODE)


def keep(token: str) -> bool:
    """Проходит ли токен в индекс."""
    return len(token) >= MIN_TOKEN_LEN and token not in STOP_TOKENS


def tokenize(text: str) -> list[str]:
    """Текст → токены, с повторами и в порядке появления.

    Повторы нужны: частота слова в документе — половина формулы BM25.

        tokenize("def is_safe_query(user_input):")
        → ['is_safe_query', 'safe', 'query', 'user_input', 'user', 'input']

    Целое имя идёт первым, части — за ним. Так один и тот же фрагмент
    находится и точным именем (редкое слово, большой вес), и вопросом
    своими словами (частое слово, малый вес) — а разбираться, что из этого
    важнее, будет IDF.
    """
    if not text:
        return []

    tokens: list[str] = []
    for match in _TOKEN.finditer(text):
        whole = match.group(0).lower()
        if keep(whole):
            tokens.append(whole)
        # Разбирается только составное имя: у `query` частей нет, и гонять
        # его через разбор — значит добавить второй такой же токен.
        for part in split_identifier(match.group(0)):
            if part != whole and keep(part):
                tokens.append(part)

    return tokens


def content_tokens(query: str) -> list[str]:
    """Только слова о ПРЕДМЕТЕ вопроса, без слов о его форме.

        content_tokens("где реализован класс ShoppingCart")
        → ['shoppingcart', 'shopping', 'cart']

    Именно по ним решается, есть ли в проекте ответ. Слова «где»,
    «реализован» и «класс» из ответа на этот вопрос ничего не сообщают:
    они есть в любом проекте, где вообще написан код.
    """
    return [token for token in tokenize_query(query) if token not in QUESTION_FRAME_TOKENS]


def tokenize_query(query: str) -> list[str]:
    """Запрос → токены без повторов.

    Повторы в запросе убираются: BM25 суммирует вклад по РАЗНЫМ словам
    запроса, и дважды написанное слово не должно весить вдвое больше.
    Порядок сохраняется — так понятнее в отладочной выдаче.
    """
    seen: set[str] = set()
    return [token for token in tokenize(query) if not (token in seen or seen.add(token))]
