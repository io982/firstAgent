"""
Слияние двух выдач: складываем места, а не оценки (пункт 6.2).

Векторный поиск вернул свою пятёрку, BM25 — свою. Их надо объединить
в один список, и первое, что приходит в голову, — сложить оценки с весами:

    score = 0.5 * близость + 0.5 * bm25          # так делать не надо

Здесь две ловушки, и обе не видны, пока не посмотришь на числа.

**Шкалы несопоставимы.** Близость — величина из отрезка [0, 1], и на этом
корпусе она почти всегда лежит между 0.6 и 0.8. BM25 ничем не ограничен
сверху: его значение зависит от размера корпуса и редкости слова, и на
точном совпадении имени доходит до 20. Складывать их — складывать
расстояние со временем.

Приведение к общей шкале не спасает, а меняет одну беду на другую.
Нормировка по максимуму внутри выдачи делает лучший результат любого списка
равным единице — независимо от того, отличный он или лучший из плохих.

**Отсутствие в списке — не ноль.** Фрагмент, который нашёл только BM25,
получил бы близость 0.0, то есть штраф, будто векторный поиск его отверг.
На деле он просто не попал в двадцатку — это разные вещи.

Reciprocal Rank Fusion обходит обе ловушки, потому что складывает НЕ ОЦЕНКИ,
А МЕСТА:

    score(фрагмент) = Σ  1 / (k + место в списке)

Сумма берётся по тем спискам, где фрагмент вообще есть. Оценки в формулу
не входят — значит приводить шкалы друг к другу не нужно вовсе. Фрагмент,
найденный обоими способами, получает два слагаемых и обгоняет тех, кого
нашёл только один. Это ровно тот сигнал, который нам нужен: согласие двух
разных поисков.

Обе функции здесь возвращают Hit с ПЕРЕСЧИТАННЫМ score. Прежние оценки
не сохраняются: после слияния они значат разное для разных фрагментов
и сравнивать их между собой уже нельзя.
"""

from chapter4.src.vectorstore import Hit

# Константа из статьи, где RRF был предложен. Она задаёт, насколько резко
# первые места отрываются от остальных: при k = 60 разница между первым
# и вторым местом (1/61 против 1/62) мала, и решает не место внутри списка,
# а то, в скольких списках фрагмент нашёлся. Уменьшать k — значит доверять
# порядку внутри списка больше, чем согласию списков.
RRF_K = 60


def rrf(rankings: list[list[Hit]], k: int = RRF_K) -> list[Hit]:
    """Сливает несколько выдач по местам. Возвращает один список, лучшее первым."""
    scores: dict[str, float] = {}
    found: dict[str, Hit] = {}

    for ranking in rankings:
        for place, hit in enumerate(ranking, 1):
            scores[hit.id] = scores.get(hit.id, 0.0) + 1.0 / (k + place)
            # Сам фрагмент берём из того списка, где он встретился первым:
            # текст и метаданные у него одни и те же, откуда бы он ни пришёл.
            found.setdefault(hit.id, hit)

    return _ordered(scores, found)


def weighted_sum(rankings: list[list[Hit]], weights: list[float] | None = None) -> list[Hit]:
    """Слияние по оценкам, приведённым к [0, 1]. Нужно для сравнения с RRF.

    Это та самая «первая мысль», которую текст главы разбирает: каждая
    выдача нормируется по своему максимуму, отсутствующим ставится ноль,
    дальше складывается с весами. Реализовано не для того, чтобы этим
    пользоваться, а чтобы замер показал разницу на числах.
    """
    weights = weights or [1.0] * len(rankings)
    if len(weights) != len(rankings):
        raise ValueError("weights должен быть той же длины, что и rankings")

    scores: dict[str, float] = {}
    found: dict[str, Hit] = {}

    for ranking, weight in zip(rankings, weights):
        if not ranking:
            continue
        best = max(hit.score for hit in ranking)
        for hit in ranking:
            # Вот она, вторая ловушка: нормируем по лучшему В ЭТОЙ ВЫДАЧЕ,
            # то есть топ-1 любого списка всегда получает 1.0 — и отличный
            # результат, и лучший из плохих.
            scores[hit.id] = scores.get(hit.id, 0.0) + weight * (hit.score / best if best else 0.0)
            found.setdefault(hit.id, hit)

    return _ordered(scores, found)


def fuse(rankings: list[list[Hit]], method: str = "rrf", **options) -> list[Hit]:
    """Слияние выбранным способом. Ручка для замеров и для агента."""
    if method == "rrf":
        return rrf(rankings, **options)
    if method == "sum":
        return weighted_sum(rankings, **options)
    raise ValueError(f"Неизвестный способ слияния: {method}. Доступны: rrf, sum")


def _ordered(scores: dict[str, float], found: dict[str, Hit]) -> list[Hit]:
    """Собирает результат: новый score, порядок по убыванию."""
    order = sorted(scores.items(), key=lambda item: -item[1])
    return [
        Hit(
            id=doc_id,
            text=found[doc_id].text,
            score=score,
            metadata=dict(found[doc_id].metadata),
        )
        for doc_id, score in order
    ]
