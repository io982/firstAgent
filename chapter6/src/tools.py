# ТОЧНОЕ ВХОЖДЕНИЕ
# ====================================================================

@tool
def grep_code(text: str) -> str:
    """Находит точные вхождения строки в файлах проекта: имя, сообщение, номер ошибки.

    Вызывай, когда нужно найти буквальный текст, а не смысл: «где встречается
    HISTORY_BUDGET», «откуда берётся сообщение про инъекцию». Ищет везде —
    в коде, комментариях и строках, а не только в определениях.

    Args:
        text: Точная строка для поиска, без кавычек
    """
    if not text or not text.strip():
        return "Ошибка: пустая строка поиска. Передай в text то, что надо найти."

    found = grep(text.strip())
    if not found:
        # Вот тот самый ноль, которого нет у векторного поиска: строки
        # в проекте действительно нет, и это проверенный факт, а не догадка.
        return (
            f"❌ Строка «{text}» в файлах проекта не встречается ни разу. "
            f"Это точный ответ, а не «не нашлось»: НЕ ВЫДУМЫВАЙ, где она могла бы быть."
        )

    shown = found[:MAX_MATCHES]
    lines = [f"{where}: {line}" for where, line in shown]
    if len(found) > len(shown):
        lines.append(f"…и ещё {len(found) - len(shown)} вхождений.")

    return (
        f"📎 Точные вхождения «{text}» ({len(found)} шт., это не поиск по смыслу). "
        "Адреса верные — называй их как есть.\n\n" + "\n".join(lines)
    )


def grep(needle: str, root: Path | str | None = None) -> list[tuple[str, str]]:
    """Ищет подстроку во всех исходниках проекта. Возвращает пары «адрес, строка».

    Обход — из Главы 5: те же пропущенные папки, тот же потолок размера
    файла, тот же разбор `.gitignore`. Регистр не учитывается, потому что
    спрашивают и `HISTORY_BUDGET`, и `history_budget`.
    """
    root = root or DEFAULT_ROOT
    lowered = needle.lower()
    found: list[tuple[str, str]] = []

    for path in iter_sources(root):
        content = read_source(path)
        if not content or lowered not in content.lower():
            continue
        relative = path.relative_to(root).as_posix()
        for number, line in enumerate(content.splitlines(), 1):
            if lowered in line.lower():
                found.append((f"{relative}:{number}", line.strip()[:MAX_LINE_CHARS]))

    return found
