"""
Инструменты Главы 6 (пункт 6.5).

Новых инструментов здесь один, а не пять. Причина — в долге Главы 5:
системный промпт вырос до 4749 токенов из 8192, и на историю разговора
осталось меньше трети окна. Каждый инструмент уезжает в промпт описанием
и сигнатурой, поэтому добавлять их по привычке больше нельзя.

Что происходит с `search_code`: он не добавляется, а ЗАМЕЩАЕТСЯ. Реестр
Главы 2 — обычный словарь «имя → функция», и повторная регистрация под
тем же именем меняет реализацию, не трогая ни промпт, ни число
инструментов. Модель по-прежнему видит `search_code`, а под ним теперь
гибридный поиск с реранкером.

Что добавляется: `grep_code` — точное вхождение строки в файлах проекта.
Ему здесь место именно потому, что это третий, самый прямолинейный способ
искать, и у него, как и у BM25, есть настоящий ноль. Таблица символов
Главы 5 находит ОПРЕДЕЛЕНИЯ по имени; `grep_code` находит любое упоминание
где угодно — в теле функции, в комментарии, в строке сообщения об ошибке.
На вопрос «где выводится вот это сообщение» ни поиск по смыслу, ни таблица
символов не отвечают, а точное вхождение отвечает сразу и без модели.
"""

import os
import sys
from pathlib import Path

sys.path.append(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

from chapter2.src.tools import tool
from chapter4.src.embeddings import EmbeddingError
from chapter5.src.languages import iter_sources, read_source
from chapter5.src.repomap import DEFAULT_ROOT
from chapter5.src.rewrite import expand_query
from chapter5.src.tools import get_code_budget

from .hybrid import TOP_K, get_hybrid_index
from .reranker import RERANK_CANDIDATES, rerank

# Сколько вхождений показывает grep_code. Больше двадцати — это уже не ответ,
# а вывод команды: частое имя встречается в проекте сотни раз.
MAX_MATCHES = 20

# Сколько символов строки показываем. Минифицированный JS и длинные строки
# данных иначе занимают выдачу целиком.
MAX_LINE_CHARS = 160


# ====================================================================
# ПОИСК ПО СМЫСЛУ И ПО СЛОВАМ
# ====================================================================

@tool
def search_code(query: str) -> str:
    """Ищет код проекта: по смыслу вопроса и по точному совпадению имён сразу.

    Вызывай, когда вопрос про устройство кода: «где считается бюджет
    контекста», «как устроена индексация», «где используется is_safe_query».
    Если нужно точное определение по имени — быстрее find_symbol.

    Args:
        query: Вопрос своими словами или имя из кода
    """
    if not query or not query.strip():
        return "Ошибка: пустой запрос. Передай в query вопрос целиком."

    index = get_hybrid_index()

    # Порог считается по ИСХОДНОМУ вопросу, до переписывания: переписанный
    # состоит из английских имён, которые модель придумала, и проверять
    # на присутствие в проекте надо не их.
    signal = index.lexical_signal(query)
    if signal.absent:
        missed = f" Не встречаются в проекте: {', '.join(signal.missing)}." if signal.missing else ""
        return (
            f"❌ В коде проекта нет ответа на «{query}».{missed} "
            f"Так и скажи пользователю. НЕ ВЫДУМЫВАЙ ни файлы, ни номера строк."
        )

    # Поиск отдаёт БОЛЬШЕ, чем уедет в контекст: реранкеру нужно из чего
    # выбирать. Он же и обрезает список до пятёрки — уже своим порядком,
    # а не порядком слияния.
    try:
        found = index.search(expand_query(query), top_k=RERANK_CANDIDATES)
        context = index.code.build_context(
            rerank(query, found, top_k=TOP_K), budget_tokens=get_code_budget()
        )
    except EmbeddingError as e:
        return (
            f"Ошибка поиска по коду: {e}. Скажи пользователю, что индекс кода "
            f"недоступен, и не отвечай по памяти."
        )

    if not context:
        return (
            f"❌ В коде проекта ничего не найдено по запросу «{query}». "
            f"Так и скажи пользователю. НЕ ВЫДУМЫВАЙ ни файлы, ни номера строк."
        )

    return (
        "🔍 Найденные фрагменты кода (совпадение по смыслу и по словам). "
        "Отвечай только по ним и обязательно назови адрес из шапки фрагмента "
        f"(файл:строки). Номера строк бери ТОЛЬКО из шапок.\n\n{context}"
    )


