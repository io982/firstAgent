"""
Разбор написанного: что не так и сделано ли то, о чём просили.

Последняя проверка конвейера и единственная, где спрашивают модель.
Все остальные механические: файл разбирается, определения не пропали,
неопределённых имён нет, тесты зелёные. Механические проверки отвечают
на вопрос «работает ли», и ни одна не отвечает на вопрос «то ли это,
о чём просили». А проваливается агент чаще всего именно там: функция
объявлена, файл импортируется, тесты зелёные — и производная, которую
просили печатать, не печатается.

Почему СХЕМА, а не «исправь». «Исправь» — просьба без критерия, и
модель, которой не сказали, что именно не так, всё равно что-нибудь
поменяет. Живой прогон это показал дважды: получив точное «имена
не определены — x», починка ответила заменой `2*a*x + b` на `2*a*x - b`.
Схема даёт то, чего в «исправь» нет: право ответить ПУСТЫМ списком,
то есть сказать «здесь всё в порядке». И заодно короткий
структурированный ответ вместо длинного свободного — форма, на которой
глава выигрывала уже трижды.

Почему каждая претензия ПРОВЕРЯЕТСЯ. Модель на 3B охотно выдумывает
проблемы, особенно если её об этом спросить. Поэтому она обязана
процитировать строку, а цитата ищется в файле: не нашлась — претензия
выбрасывается молча, до того как по ней что-то менять. Тот же приём,
что у якоря правки и у `validate_plan`, и та же причина: не спорить
с моделью, а отсеивать непроверяемое.

Почему мнение модели НЕ откатывает работу. Механическая проверка
говорит о факте, разбор — о мнении, и цена ошибки у них разная.
Красные тесты — повод вернуть файлы как было; «мне кажется, задача
не выполнена» — повод сказать об этом человеку. Работу, прошедшую
все механические проверки, из-за мнения не удаляют.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass

from chapter1.agent import request_model
from chapter8.src import guard

# Разбор написанного: "on" — спрашивать модель, "off" — не спрашивать.
#
# ВЫКЛЮЧЕН по умолчанию, и это решение замера, а не осторожность.
# Замер 9 (TestReviewQuality) на шести подготовленных случаях, по два
# прогона. Файлы подобраны так, что все механические проверки главы
# их пропускают:
#
#     модель                    поймал беду   промолчал, где надо
#     qwen2.5:3b                        0/8                   4/4
#     qwen2_5coder3b_q5                 0/8                   4/4
#     qwen2.5-coder:3b                  0/8                   4/4
#     qwen2.5-coder:7b                  5/8                   3/4
#     llama3.1:8b                       0/8                   4/4
#
# На 3B разбор не ловит НИЧЕГО. Ни мёртвой функции, ни вызова, который
# не сходится с определением, ни пропущенного `input` — при том что
# каждая беда названа в правилах прямым текстом. Вторая колонка при
# этом идеальная, и она же объясняет первую: модель отвечает «сделано»
# всегда, а не потому, что проверила.
#
# С 7B приём начинает работать: пять бед из восьми, одна ложная
# тревога, 78 секунд против 24. Отсюда и переключатель: на модели
# курса включать нечего, на модели покрупнее — есть что.
#
# Вывод шире одного приёма и совпадает с выводом замера 6: **слабая
# модель не становится сильнее оттого, что её спрашивают о своей же
# работе.** Схема даёт ей форму ответа, но не даёт того, чего нет, —
# способности заметить.
REVIEW = os.environ.get("AGENT_REVIEW", "off")

# Сколько претензий принимать. Не про токены: список из десяти пунктов
# от модели на 3B — это признак того, что она начала перечислять
# всё подряд, а не то, что в файле десять ошибок.
MAX_PROBLEMS = 3

REVIEW_RULES = """Ты проверяешь, сделано ли то, о чём просил человек. Кода не пишешь.

Отвечай двумя полями:
1. done — выполнена ли задача целиком. Если сомневаешься, ставь false.
2. problems — что мешает считать её выполненной. Нечего сказать — пустой список.

Про каждую претензию:
* quote — строка из файла ЦЕЛИКОМ и ДОСЛОВНО, к которой претензия.
  Не придумывай строк: их сверят с файлом, и выдуманные выбросят.
* what — что не так, одной фразой.
* how — что сделать, одной фразой.

Что считается невыполненным:
* просили печатать — а нигде нет print;
* просили спрашивать у человека — а нигде нет input;
* функция написана, но её никто не вызывает;
* сделано не то, о чём просили, а что-то похожее.

Работающий код, который делает ровно то, о чём просили, — это done=true
и пустой список. Придираться к стилю не надо."""


@dataclass
class Problem:
    """Одна претензия к написанному."""

    quote: str
    what: str
    how: str = ""

    def line(self) -> str:
        return f"{self.what} (строка: {self.quote.strip()})" + (f" — {self.how}" if self.how else "")


def review_schema() -> dict:
    """Схема разбора: сделано ли, и если нет — что именно мешает."""
    return {
        "type": "object",
        "properties": {
            "done": {"type": "boolean"},
            "problems": {
                "type": "array",
                "maxItems": MAX_PROBLEMS,
                "items": {
                    "type": "object",
                    "properties": {
                        "quote": {"type": "string"},
                        "what": {"type": "string"},
                        "how": {"type": "string"},
                    },
                    "required": ["quote", "what"],
                },
            },
        },
        "required": ["done", "problems"],
    }


def review(task: str, path: str, model_call=None) -> tuple[bool, list[Problem]]:
    """Смотрит на файл глазами задачи. Пара «сделано, список претензий».

    `model_call` подменяется в тестах: разбор — единственное место
    конвейера, где мнение модели влияет на исход, и проверять его
    надо без модели.

    При любой беде со стороны модели возвращается «сделано, претензий
    нет». Это не оптимизм, а порядок приоритетов: механические проверки
    уже прошли, и молчание разбора не должно превращать зелёный прогон
    в красный.
    """
    text = _text_of(path)
    if not text.strip():
        return True, []

    numbered = "\n".join(f"{n}| {line}" for n, line in enumerate(text.splitlines(), 1))
    messages = [
        {"role": "system", "content": REVIEW_RULES},
        {"role": "user", "content": f"Файл {path}:\n{numbered}\n\nЗадача человека: {task}"},
    ]
    ask = model_call or request_model
    try:
        answer = json.loads(ask(messages, response_format=review_schema()))
    except Exception:  # noqa: BLE001
        return True, []

    problems = verified_problems(answer.get("problems", []), text)
    done = bool(answer.get("done", True))
    # Претензий не осталось — значит, сказать нечего, что бы ни стояло
    # в `done`. Иначе прогон уходил бы в починку без единого указания,
    # что чинить, — то самое «исправь» без критерия, от которого
    # разбор и придуман.
    return (True, []) if not problems else (done, problems)


def verified_problems(raw: list, text: str) -> list[Problem]:
    """Оставляет только те претензии, чью цитату видно в файле.

    Сверка по строке целиком не годится: модель переставляет пробелы
    и теряет отступ. Сравниваются строки без крайних пробелов, и этого
    достаточно — выдуманную строку так не подтвердить.
    """
    lines = {line.strip() for line in text.splitlines() if line.strip()}
    found: list[Problem] = []
    for item in raw[:MAX_PROBLEMS]:
        if not isinstance(item, dict):
            continue
        quote = str(item.get("quote", "")).strip()
        what = str(item.get("what", "")).strip()
        if not quote or not what or quote not in lines:
            continue
        found.append(Problem(quote=quote, what=what, how=str(item.get("how", "")).strip()))
    return found


def report(problems: list[Problem]) -> str:
    """Претензии одним текстом — он уезжает в починку и в отчёт человеку."""
    return "\n".join(f"- {problem.line()}" for problem in problems)


def _text_of(path: str) -> str:
    try:
        return guard.resolve_path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError, guard.OutsideWorkspace):
        return ""
