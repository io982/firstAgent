@dataclass
class Change:
    """Одна правка файла: путь и его содержимое ДО неё."""

    path: Path
    before: str | None  # None — файла не существовало


_CHANGES: list[Change] = []


def record(path: str | Path) -> None:
    """Запоминает файл перед изменением.

    Читает содержимое сам, а не принимает его параметром: вызывающему
    легко забыть прочитать файл до записи, и тогда в журнал попадёт
    уже новое состояние — откат вернул бы файл в него же.
    """
    p = Path(path)
    try:
        before = p.read_text(encoding="utf-8") if p.exists() else None
    except (OSError, UnicodeDecodeError):
        # Двоичный или недоступный файл откатить текстом нельзя, и делать
        # вид, что можно, хуже, чем не записать его в журнал.
        return
    _CHANGES.append(Change(path=p, before=before))

    # То же самое, но в git и на диск: список выше умрёт вместе
    # с процессом, а журнал и снимок переживут. Если каталог не
    # репозиторий, остаётся только список — и агент говорит об этом
    # человеку, а не делает вид, что защищён (см. history.py).
    root = get_workspace()
    if history.available(root):
        history.remember(root, p, before)


def change_count() -> int:
    """Сколько правок записано в журнал — со всеми повторами.

    Не то же самое, что длина `changed_files()`: тот список без
    повторов, а здесь считается каждая правка. Разница нужна тому,
    кто спрашивает «легла ли ПОСЛЕДНЯЯ правка на диск»: второй раз
    правленный файл список уникальных путей не удлиняет, и по нему
    вторая правка выглядела бы как несостоявшаяся.
    """
    return len(_CHANGES)


def changed_files() -> list[Path]:
    """Файлы, которых агент касался, без повторов и в порядке первой правки."""
    seen: list[Path] = []
    for change in _CHANGES:
        if change.path not in seen:
            seen.append(change.path)
    return seen


def forget_changes() -> None:
    """Очищает журнал. Вызывается после коммита и в начале нового прогона.

    Ветку со снимком не трогает: она принадлежит человеку, а не
    прогону. Прогон, который упал и не откатился, оставляет её в
    репозитории — и вернуться к тому состоянию можно и без агента.
    """
    _CHANGES.clear()
    history.clear()


def rollback() -> list[str]:
    """Возвращает все тронутые файлы в исходное состояние.

    В обратном порядке — и это не украшение. Файл, правленный дважды,
    лежит в журнале дважды: сначала исходный текст, потом промежуточный.
    Идя с конца, мы последним применяем самый ранний снимок и получаем
    состояние ДО первой правки, а не до последней.
    """
    # Отчёт собирается словарём, а сами восстановления делаются все.
    # Файл, правленный дважды, лежит в журнале дважды: применить надо
    # оба снимка (чтобы дойти до самого раннего), а сказать о нём
    # человеку — один раз. «восстановлен код.py, восстановлен код.py»
    # выглядит как ошибка отката, хотя откат как раз отработал верно.
    # Журнал на диске сильнее списка в памяти, и в этом весь смысл
    # затеи: он переживает перезапуск агента. Список остаётся
    # запасным ходом для каталогов без git.
    root = get_workspace()
    if history.pending(root):
        done = history.restore(root)
        _CHANGES.clear()
        return done

    restored: dict[str, str] = {}
    for change in reversed(_CHANGES):
        name = relative(change.path)
        try:
            if change.before is None:
                if change.path.exists():
                    change.path.unlink()
                    restored[name] = f"удалён {name}"
            else:
                change.path.parent.mkdir(parents=True, exist_ok=True)
                change.path.write_text(change.before, encoding="utf-8")
                restored[name] = f"восстановлен {name}"
        except OSError as exc:
            restored[name] = f"НЕ ОТКАЧЕН {name}: {exc}"
    _CHANGES.clear()
    return list(restored.values())
