def _same_or_inside(candidate: Path, root: Path) -> bool:
    """Лежит ли candidate внутри root — с поправкой на регистр Windows.

    Сравнение делается через normcase, потому что на Windows два
    написания одного пути различаются только регистром буквы диска,
    а как строки они разные. На Linux normcase ничего не меняет,
    и правило остаётся тем же.
    """
    c = os.path.normcase(str(candidate))
    r = os.path.normcase(str(root))
    return c == r or c.startswith(r.rstrip(os.sep) + os.sep)


def resolve_path(path: str | Path) -> Path:
    """Путь внутри рабочего каталога — или исключение.

    Три способа выйти за корень, и все три закрываются здесь:

      * `../../etc/passwd` — снимается разворачиванием пути (`resolve`);
      * абсолютный путь в другой каталог — проверкой на вхождение;
      * символическая ссылка наружу — тем же `resolve`, который ссылки
        разворачивает до настоящего места.

    Отдельно отвергается `~`: домашний каталог почти наверняка лежит вне
    рабочего, и расширять тильду значит выдавать пропуск наружу.
    """
    raw = str(path).strip()
    if not raw:
        raise OutsideWorkspace("Пустой путь")
    if raw.startswith("~"):
        raise OutsideWorkspace(f"Путь через домашний каталог запрещён: {raw}")

    root = _POLICY.root
    candidate = Path(raw)
    if not candidate.is_absolute():
        candidate = root / candidate

    # strict=False: файла может ещё не быть — write_file как раз его создаёт.
    # Разворачивание при этом работает и для несуществующих путей.
    candidate = candidate.resolve(strict=False)
    root = root.resolve(strict=False)

    if not _same_or_inside(candidate, root):
        raise OutsideWorkspace(
            f"Путь ведёт за пределы рабочего каталога.\n"
            f"  запрошено: {raw}\n"
            f"  это:       {candidate}\n"
            f"  корень:    {root}"
        )
    return candidate


def relative(path: str | Path) -> str:
    """Путь относительно корня — для сообщений человеку и модели.

    Модели в контекст уезжает короткий путь, а не полный: во-первых,
    он занимает меньше места, во-вторых, полный содержит имя
    пользователя и структуру диска, которым в контексте делать нечего.
    """
    try:
        return Path(path).resolve(strict=False).relative_to(_POLICY.root).as_posix()
    except ValueError:
        return str(path)


