def split_command(command: str) -> list[str]:
    """Разбирает командную строку на программу и аргументы.

    posix=False на Windows: разборщик в posix-режиме считает обратную
    косую черту экранированием, и путь с разделителями Windows теряет их
    вместе с частью имени. Кавычки при этом остаются внутри токенов,
    поэтому их снимаем отдельно.
    """
    posix = os.name != "nt"
    parts = shlex.split(command, posix=posix)
    if posix:
        return parts
    return [p.strip('"') for p in parts]


def program_of(command: str) -> str:
    """Имя программы, которую на самом деле просят запустить.

    Отдельной функцией, потому что «имя программы» — не первое слово
    строки. И полный путь к интерпретатору, и `python -m pytest`
    должны сверяться со списком так же, как короткое `pytest`,
    иначе список пришлось бы писать в трёх формах на каждую программу.
    """
    try:
        parts = split_command(command)
    except ValueError:
        return ""
    if not parts:
        return ""
    program = Path(parts[0]).stem.lower()
    if program == "python" and len(parts) >= 3 and parts[1] == "-m":
        program = Path(parts[2]).stem.lower()
    return program


def command_allowed(command: str) -> tuple[bool, str]:
    """Пускать ли команду. Вторым значением — причина отказа."""
    for bad in SHELL_CHARS:
        if bad in command:
            return False, (
                f"В команде есть '{bad}' — это синтаксис командной оболочки, "
                "а команды запускаются напрямую, без неё. Разбейте на отдельные вызовы."
            )
    try:
        parts = split_command(command)
    except ValueError as exc:
        return False, f"Команду не удалось разобрать: {exc}"
    if not parts:
        return False, "Пустая команда"

    program = program_of(command)
    if program in SHELL_BUILTINS:
        return False, (
            f"'{program}' — встроенная команда оболочки, а не программа: запустить её "
            "напрямую нельзя. Рабочий каталог у агента один и меняется командой «каталог»."
        )

    if _POLICY.allowed is None:
        return True, ""

    if program not in _POLICY.allowed:
        return False, (
            f"Программа '{program}' не в белом списке. Разрешены: "
            f"{', '.join(_POLICY.allowed)}"
        )
    return True, ""


