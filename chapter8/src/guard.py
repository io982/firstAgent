def confirm_in_terminal(action: str, detail: str) -> bool:
    """Спрашивает человека в терминале. Ответ по умолчанию — «нет».

    По умолчанию «нет» именно потому, что нажать Enter проще всего:
    случайный Enter должен означать отказ, а не согласие.
    """
    print(f"\n  Агент собирается: {action}")
    print(f"  Подробности: {detail}")
    answer = input("  Разрешить? [y/N] ").strip().lower()
    return answer in ("y", "yes", "д", "да")


@dataclass
class Policy:
    """Все ограничения одним объектом.

    Одним объектом — чтобы «в каком режиме сейчас работает агент» был
    один вопрос с одним ответом. Разложенные по модулям флаги имеют
    свойство расходиться: тест правит один, код читает другой.
    """

    root: Path = field(default_factory=Path.cwd)
    mode: str = ASK
    dry_run: bool = False
    timeout: float = DEFAULT_TIMEOUT
    allowed: tuple[str, ...] | None = ANY_COMMAND
    confirm: Callable[[str, str], bool] = confirm_in_terminal


def _default_policy() -> Policy:
    """Политика при старте: корень из AGENT_WORKSPACE или текущий каталог."""
    root = os.environ.get("AGENT_WORKSPACE") or os.getcwd()
    return Policy(root=Path(root).resolve())


_POLICY = _default_policy()


def get_policy() -> Policy:
    """Текущая политика."""
    return _POLICY


def set_policy(**changes) -> Policy:
    """Меняет названные поля политики, остальные оставляет как есть.

    Возвращает НОВЫЙ объект и делает его текущим. Политика заменяется
    целиком по той же причине, по какой она одна: правку через
    `policy.dry_run = True` невозможно заметить со стороны, а вызов
    set_policy — можно.
    """
    global _POLICY
    if changes.get("root") is not None:
        changes["root"] = Path(changes["root"]).resolve()
        # Каталог сменился — прежние ответы про него к новому отношения
        # не имеют: ни «репозиторий или нет», ни разрешение на conftest.py.
        history.forget_available()
        forget_conftest()
    _POLICY = replace(_POLICY, **changes)
    return _POLICY


def reset_policy() -> Policy:
    """Возвращает политику к состоянию «как при импорте». Нужно тестам."""
    global _POLICY
    _POLICY = _default_policy()
    return _POLICY


def set_workspace(path: str | Path) -> Path:
    """Назначает рабочий каталог. Короткая запись для частого случая."""
    return set_policy(root=path).root


def get_workspace() -> Path:
    """Рабочий каталог."""
    return _POLICY.root


