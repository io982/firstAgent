"""
Границы кодинг-агента: куда можно писать, что можно запускать, что спросить.

До этой главы агент только читал и считал. Здесь он получает право
перезаписать файл и запустить процесс — и это меняет цену ошибки.
Ошибка поиска стоит плохого ответа; ошибка записи стоит файла.

Поэтому модуль пишется первым, до самих инструментов: пока нет ответа
на вопрос «а что будет, если модель попросит переписать системный
каталог», писать `write_file` рано.

Пять ограничений, каждое закрывает свой способ навредить:

  * **рабочий каталог** — один корень, за его пределы пути не выходят;
  * **белый список команд** — механизм есть, но ПО УМОЛЧАНИЮ ВЫКЛЮЧЕН,
    см. `ANY_COMMAND` ниже;
  * **предел по времени** — процесс, который завис, снимается;
  * **сухой прогон** — режим, в котором агент говорит, что сделал бы,
    и не делает;
  * **подтверждение человеком** — перед каждым действием, которое меняет
    диск, ставит пакеты или запускает команду.

Второе ограничение выключено осознанно, и цену этого стоит понять
до того, как запускать агента. Кодинг-агент, который создаёт проекты
и разбирается с зависимостями, заранее не знает, какая программа ему
понадобится, — а список, который приходится дописывать под каждую
задачу, защитой быть перестаёт. Взамен остаются рабочий каталог
и человек, читающий команду перед тем, как нажать `y`. Значит, читать
её придётся всерьёз: другой проверки больше нет.

Это не модель угроз, а её нижняя граница: то, без чего нельзя запускать
сгенерированный код на своей машине. Права инструментов, песочница
и полный разбор угроз — отдельная тема, и здесь её нет.

Журнал изменений (`record`, `rollback`) живёт тоже здесь, а не в файловых
инструментах: откат нужен и конвейеру правки, и git-коммиту, и человеку,
который передумал. Один журнал на всех.

Хранится он в двух местах, и это не дублирование. Список в памяти
отвечает на вопрос «что агент трогал в этом прогоне» — его спрашивают
и конвейер, и git-коммит, и он обязан быть быстрым. Прежнее содержимое
файлов уходит в git и в журнал на диске (см. history.py) — там оно
переживает перезапуск агента, а список в памяти нет. Где git взять
неоткуда, остаётся только список, и агент говорит об этом вслух.
"""
from __future__ import annotations

import os
import shlex
from collections.abc import Callable
from dataclasses import dataclass, field, replace
from pathlib import Path

from chapter8.src import history

# --------------------------------------------------------------------
# ИСХОДЫ ПРОВЕРКИ
# --------------------------------------------------------------------
# Три, а не два. «Можно» и «нельзя» не описывают сухой прогон: там
# действие разрешено и всё равно не происходит, и сказать об этом
# человеку надо иначе, чем об отказе.
ALLOW = "allow"
DRY = "dry"
DENIED = "denied"

# Режимы подтверждения.
ASK = "ask"      # спросить человека
AUTO = "auto"    # разрешать молча — для тестов и неинтерактивных прогонов
DENY = "deny"    # запретить всё, что меняет диск

# Программы, которые агенту разрешено запускать. Список короткий
# намеренно: он не «на всякий случай», а «ровно то, что нужно
# кодинг-агенту курса» — запустить код, прогнать тесты, проверить
# линтером, посмотреть историю, поставить зависимость.
#
# Честная оговорка: белый список ограничивает ПРОГРАММЫ, а не то, что
# они делают. `python` в списке — значит, любой код на Python агенту
# доступен. Это не дыра в реализации, а граница самого приёма: агент,
# который умеет запускать код, умеет запускать код.
NARROW_ALLOWED = ("python", "pytest", "ruff", "git", "pip")

# Каталоги, в которые агент не заходит. Не запрет, а гигиена: в `.git`
# и `__pycache__` лежат не исходники, а их производные, и попадание их
# в контекст стоит места и не даёт ничего. Живёт здесь, а не в файловых
# инструментах, потому что тем же списком пользуется поиск conftest.py
# ниже, а `guard` не имеет права импортировать то, что импортирует его.
SKIP_DIRS = frozenset(
    {".git", "__pycache__", ".venv", "venv", "node_modules", "chroma_db", ".pytest_cache", ".ruff_cache"}
)

# `allowed = ANY_COMMAND` означает «белого списка нет».
#
# И это умолчание главы. Решение осознанное и стоит того, чтобы назвать
# его цену вслух: агент, который создаёт проекты с нуля, ставит
# зависимости и разбирается с окружением, заранее не знает, какая
# программа ему понадобится. Список из пяти имён такой агент упирает
# в стену на первой же непредусмотренной команде, а список из пятидесяти
# защитой уже не является — он просто длиннее.
#
# Что остаётся вместо него: рабочий каталог, за который агент не выходит,
# и подтверждение человеком перед КАЖДОЙ командой, с показом самой
# команды. То есть последней проверкой становится человек, читающий
# строку перед тем, как нажать `y`. Подтверждение, которое жмут не
# глядя, защитой быть перестаёт — и теперь это единственная защита.
#
# Узкий список никуда не делся и включается одной строкой:
#
#     guard.set_policy(allowed=guard.NARROW_ALLOWED)
ANY_COMMAND: tuple[str, ...] | None = None

# Признаки того, что модель имела в виду командную оболочку, а не одну
# программу. Мы запускаем процесс напрямую, без оболочки, поэтому такие
# символы всё равно приехали бы внутрь как обычный текст аргумента —
# и команда тихо сделала бы не то. Лучше отказать вслух.
SHELL_CHARS = (";", "&&", "||", "|", ">", "<", "`", "$(", "\n")

# Встроенные команды оболочки. Программами они не являются: их исполняет
# сам cmd или sh, а мы запускаем процессы напрямую. Запустить `cd`
# нельзя в принципе — не потому, что не разрешили, а потому, что такой
# программы нет. Отдельный список нужен ради внятного отказа: без него
# человек видит «Программа не найдена: cd» и думает, что чего-то не хватает.
#
# `cd` в этом списке главный. Рабочий каталог у агента один и меняется
# командой «каталог», а не изнутри плана: команда, сменившая каталог
# в дочернем процессе, к следующей команде уже забыта.
SHELL_BUILTINS = frozenset(
    {"cd", "chdir", "dir", "echo", "set", "cls", "copy", "del", "type",
     "export", "source", "alias", "pushd", "popd"}
)

# Предел по времени на один запуск, секунды.
DEFAULT_TIMEOUT = 30.0


class OutsideWorkspace(Exception):
    """Путь ведёт за пределы рабочего каталога."""


