"""
Три формы правки файла — и почему их именно три.

Это центральное место главы. Всё остальное у кодинг-агента похоже на то,
что уже было: прочитать файл он умел с Главы 2, найти нужное место —
с Главы 5. Новое здесь ровно одно: сказать, ЧТО именно поменять, — и
слабая модель ломается как раз тут.

Форм, которыми это говорят, придумано три, и каждая проваливается
по-своему:

  1. **Перезапись целиком** — модель выдаёт новый текст файла.
     Просто и всегда применимо. Проваливается на длине: файл в двести
     строк модель на 3B перепечатывает не целиком, и вместе с правкой
     тихо пропадают куски, которые никто не просил трогать.

  2. **Замена по якорю** — модель выдаёт кусок «как было» и кусок
     «как стало». Короткая, и потерять чужой код физически не может.
     Проваливается на точности цитаты: якорь должен совпасть с файлом
     до символа, включая отступы и переводы строк.

  3. **Замена диапазона строк** — модель выдаёт номера строк и новый
     текст. Цитировать ничего не надо, и это её главное преимущество
     на слабой модели. Требует точного адреса — а адрес у нас уже есть:
     поиск по коду из Главы 5 отвечает в виде `файл:строки`, и здесь
     этот ответ используется как вход.

Ни одна из трёх не «правильная»: у каждой свой способ не сработать.
Поэтому реализованы все три с общим результатом, а какую выдаёт
применимой чаще конкретная модель — вопрос замера, а не вкуса.

Замер главы дал резкий ответ, и он противоречит ожиданию. На файле
из одной функции все три формы работают одинаково хорошо. На том же
файле, обложенном девятью посторонними функциями, форма `anchor`
держится, а `lines` и `full` перестают работать совсем — по разным
причинам, которые дают один и тот же результат: из файла пропадает
определение, которое никто не просил трогать. Поэтому промпт правки
по умолчанию просит цитату, а не номера строк, хотя номера у нас
и есть, и выглядят они удобнее.

Отдельно про схему ответа. Она собрана из трёх вариантов через `oneOf`,
по одному на форму, и это тоже вывод замера, а не проектное изящество.
Схема с общим набором полей, где обязательны только `form` и `path`,
разрешает модели назвать одну форму и заполнить поля другой — и слабая
модель ровно так и делает. `enum` ограничивает значение поля, а не смысл
ответа; связь между полями выражается структурой схемы или не выражается
вовсе. Подробности в `edit_schema()`.

Отдельно: правка считается неприменённой, если после неё файл перестал
разбираться (`syntax_ok`) или из него пропали определения
(`lost_definitions`). Синтаксически сломанный файл — это не «частично
правильная правка», это отсутствие правки плюс испорченный файл;
файл без половины функций — то же самое, только выглядит целым.
"""
from __future__ import annotations

import ast
import difflib
import textwrap
from dataclasses import dataclass

# Имена форм. Строками, а не Enum: они уезжают в JSON плана и в отчёт
# замера, и лишнее преобразование на каждой границе того не стоит.
ANCHOR = "anchor"
LINES = "lines"
FULL = "full"
APPEND = "append"

# Три формы ЗАМЕНЯЮТ кусок файла, четвёртая ДОПИСЫВАЕТ в конец.
# Разделение нужно замеру: сравнивать между собой имеет смысл только
# первые три, они решают одну задачу разными способами. Дописывание
# решает другую и в этом сравнении не участвует.
REPLACING_FORMS = (ANCHOR, LINES, FULL)
EDIT_FORMS = (*REPLACING_FORMS, APPEND)


@dataclass
class EditResult:
    """Исход одной правки.

    `text` заполнен всегда — при провале это прежний текст, не пустая
    строка. Вызывающему тогда не приходится помнить, что при `ok=False`
    поле смотреть нельзя: испортить файл «пустым результатом» просто
    нечем.
    """

    ok: bool
    message: str
    text: str
    form: str = ""


def _newline_of(text: str) -> str:
    """Какими переводами строк написан файл.

    Нужно потому, что модель отвечает через `\\n` всегда, а файл,
    созданный на Windows, хранит `\\r\\n`. Якорь из ответа модели тогда
    не совпадает с файлом ни одним символом переноса — и правка
    проваливается по причине, не имеющей отношения к её содержанию.
    """
    return "\r\n" if "\r\n" in text else "\n"


def apply_anchor(text: str, old: str, new: str) -> EditResult:
    """Заменяет ЕДИНСТВЕННОЕ вхождение `old` на `new`.

    Единственное — это условие, а не оптимизация. Якорь, встречающийся
    дважды, не адресует место: заменить первое вхождение и заменить
    второе — разные правки, и выбирать за модель мы не вправе. Поэтому
    вместо угадывания возвращается отказ с числом вхождений, и модель
    получает понятное указание — удлинить якорь.
    """
    if not old:
        return EditResult(False, "Пустой якорь: нечего искать.", text, ANCHOR)
    if old == new:
        return EditResult(False, "Якорь и замена совпадают — правка ничего не меняет.", text, ANCHOR)

    eol = _newline_of(text)
    candidate = old
    replacement = new
    count = text.count(candidate)

    # Вторая попытка — с переводами строк файла. Ровно тот случай,
    # ради которого написан _newline_of().
    if count == 0 and eol != "\n":
        candidate = old.replace("\n", eol)
        replacement = new.replace("\n", eol)
        count = text.count(candidate)

    if count == 0:
        return EditResult(False, f"{ANCHOR_MISSED}.{_nearest(text, old)}", text, ANCHOR)
    if count > 1:
        return EditResult(
            False,
            f"Якорь встречается {count} раз — он не указывает на одно место. "
            "Возьмите кусок длиннее, чтобы он стал единственным.",
            text,
            ANCHOR,
        )

    return EditResult(True, "Заменено одно вхождение якоря.", text.replace(candidate, replacement, 1), ANCHOR)


def _nearest(text: str, old: str) -> str:
    """Подсказка «а не это ли вы имели в виду» к ненайденному якорю.

    Модель, получившая просто «не найдено», повторяет тот же якорь.
    Получившая похожую строку из файла — обычно исправляет отступ или
    кавычки и попадает со второй попытки.
    """
    first = old.strip().splitlines()[0] if old.strip() else ""
    if not first:
        return ""
    close = difflib.get_close_matches(first, text.splitlines(), n=1, cutoff=0.6)
    if not close:
        return ""
    return f"\n  Похожая строка в файле: {close[0]!r}\n  Ваш якорь начинается с: {first!r}"


def apply_lines(text: str, start: int, end: int, content: str) -> EditResult:
    """Заменяет строки с `start` по `end` включительно на `content`.

    Нумерация с единицы и оба конца включительно — потому что именно так
    адрес печатает поиск по коду из Главы 5 (`agent.py:120-145`).
    Переводить одно представление в другое пришлось бы модели, а это
    ровно тот вид работы, на котором 3B ошибается.
    """
    lines = text.splitlines(keepends=True)
    total = len(lines)

    if start < 1:
        return EditResult(False, f"Строка {start}: нумерация начинается с 1.", text, LINES)
    if end < start:
        return EditResult(False, f"Конец диапазона ({end}) раньше начала ({start}).", text, LINES)
    if start > total:
        return EditResult(False, f"В файле {total} строк, а правка начинается со строки {start}.", text, LINES)
    if end > total:
        return EditResult(False, f"В файле {total} строк, а правка кончается на строке {end}.", text, LINES)

    eol = _newline_of(text)
    plain, indent = _restore_indent(lines[start - 1 : end], content.replace("\r\n", "\n"))
    body = plain.replace("\n", eol)
    # Перевод строки в конце вставки нужен всегда, кроме случая, когда
    # заменяется последняя строка файла, а сам файл им не кончался.
    tail_had_eol = lines[end - 1].endswith(("\n", "\r"))
    if body and not body.endswith(eol) and (end < total or tail_had_eol):
        body += eol

    new_text = "".join(lines[: start - 1]) + body + "".join(lines[end:])
    if new_text == text:
        return EditResult(False, "Правка ничего не меняет: текст совпадает с прежним.", text, LINES)

    replaced = end - start + 1
    note = f" Отступ восстановлен ({indent} пробела/ов)." if indent else ""
    return EditResult(True, f"Заменены строки {start}-{end} ({replaced} шт.).{note}", new_text, LINES)


def _restore_indent(replaced: list[str], content: str) -> tuple[str, int]:
    """Возвращает отступ строкам замены, если модель его потеряла.

    Самая частая поломка формы `lines` на модели в 3B, и она не про
    понимание задачи. Модель правильно находит строку и правильно
    пишет код, но отвечает `return a + b` вместо `    return a + b` —
    отступ теряется где-то между чтением файла и составлением ответа.
    В Python это не косметика: файл после такой правки перестаёт
    разбираться, `syntax_ok` его отвергает, и попытка сгорает впустую.

    Промптом не чинится: правило про отступы в EDIT_RULES стоит, и
    модель нарушает его всё равно. Поэтому чинится здесь, и правило
    намеренно узкое: отступ добавляется, только если в замене НЕТ
    отступа ни на одной строке, а у заменяемого куска общий отступ
    был. Модель, расставившая отступы сама, знает, что делает,
    и трогать её не надо.

    Возвращает исправленный текст и величину добавленного отступа
    (ноль — ничего не добавлялось). Величина уезжает в отчёт: правка
    файла, сделанная не по букве ответа модели, должна быть видна,
    а не происходить молча.
    """
    body = content.split("\n")
    meaningful = [line for line in body if line.strip()]
    if not meaningful or any(line[:1] in (" ", "\t") for line in meaningful):
        return content, 0

    indents = [len(line) - len(line.lstrip()) for line in replaced if line.strip()]
    indent = min(indents) if indents else 0
    if indent <= 0:
        return content, 0

    pad = " " * indent
    return "\n".join(pad + line if line.strip() else line for line in body), indent


def apply_full(text: str, content: str) -> EditResult:
    """Заменяет содержимое файла целиком.

    Отдельная проверка на резкое укорочение — от главной беды этой формы.
    Модель, которой велели «поправить одну функцию», нередко возвращает
    только её, и файл теряет всё остальное. Молча записать такое нельзя,
    а отличить от честного сокращения кода — можно только по размеру,
    поэтому предупреждение, а не отказ.
    """
    if content == text:
        return EditResult(False, "Правка ничего не меняет: текст совпадает с прежним.", text, FULL)

    note = ""
    # Весь файл с лишним отступом слева — беда механическая, и чинится
    # она так же механически, как у дописывания. Живой прогон:
    # на «исправь все ошибки» модель вернула файл целиком, сдвинутый
    # на четыре пробела, и правка отменилась с «строка 1: unexpected
    # indent». Отменять то, что чинится одним `dedent`, — терять работу
    # на форматировании.
    if content[:1].isspace() and not syntax_ok("x.py", content)[0]:
        flat = textwrap.dedent(content)
        if syntax_ok("x.py", flat)[0]:
            content = flat
            note = " (снят лишний отступ у всего файла)"

    was, became = len(text.splitlines()), len(content.splitlines())
    if was >= 20 and became < was * 0.5:
        note = (
            f" ВНИМАНИЕ: было {was} строк, стало {became} — "
            "перезапись целиком часто теряет код, которого не просили трогать."
        )
    return EditResult(True, f"Файл перезаписан целиком ({was} -> {became} строк).{note}", content, FULL)


def apply_append(text: str, content: str) -> EditResult:
    """Дописывает `content` в конец файла.

    Четвёртая форма, и появилась она не из проектирования, а из живой
    задачи. Человек попросил «добавить в calc.py интерактивность»,
    и модель ответила якорем с ПУСТЫМ `old` — то есть попыталась сказать
    «просто допиши вот это», не имея для такой мысли формы. Правка
    не применилась, круг сгорел.

    Своя форма нужна ей потому, что «дописать в конец» через замену
    выражается плохо: якорем надо процитировать последнюю строку файла
    (её ещё надо угадать), номерами — назвать номер последней строки
    (её надо посчитать), перезаписью — перепечатать файл целиком
    (а это форма, которая теряет чужой код). Требовать от модели в 3B
    любой из трёх обходных путей значит требовать лишней работы там,
    где задача элементарна.

    Потерять чужой код эта форма не может по устройству — она ничего
    не удаляет. Испортить файл может: приписанный текст должен
    разбираться вместе с уже написанным, и это проверяет `syntax_ok`
    на общем пути записи.
    """
    if not content.strip():
        return EditResult(False, "Нечего дописывать: пустой текст.", text, APPEND)

    eol = _newline_of(text)
    # Ведущие и хвостовые переводы строк срезаются: разделитель между
    # старым и новым ставим мы, и если ответ модели начинается с пустой
    # строки, их станет две подряд. Отступ первой строки при этом
    # не трогается — `strip` снимает только переводы.
    plain = content.replace("\r\n", "\n").strip("\n")
    body = plain.replace("\n", eol) + eol

    # Пустая строка между старым и новым, если её там ещё нет: без неё
    # приписанная функция слипается с последней строкой файла, и Python
    # это уже не разбирает.
    head = text
    if head.strip():
        if not head.endswith(eol):
            head += eol
        if not head.endswith(eol + eol):
            head += eol

    note = ""
    # Определение, уехавшее внутрь чужого блока, — это сбитый отступ,
    # и чинится он механически. Живой прогон: на «добавь производную»
    # модель раз за разом отвечала телом с четырьмя пробелами, и `def`
    # приклеивался к блоку `if __name__`, стоявшему в конце файла.
    # Функция после этого объявляется только внутри условия и не зовётся
    # никогда. Просить модель ещё раз бесполезно — три захода подряд
    # дали один и тот же отступ; снять его кодом и сказать об этом
    # честнее и дешевле. Приём тот же, что у `normalize_edit`: понять
    # ответ модели не буквально, но не молча.
    if plain[:1].isspace() and _stray_names(text, head + body):
        flat = textwrap.dedent(plain)
        candidate = head + flat.replace(chr(10), eol) + eol
        if not _stray_names(text, candidate) and syntax_ok("x.py", candidate)[0]:
            body = flat.replace(chr(10), eol) + eol
            note = " (снят лишний отступ: определения ставятся на верхний уровень)"

    added = len(body.strip().splitlines())
    return EditResult(True, f"Дописано в конец файла ({added} строк).{note}", head + body, APPEND)


def syntax_ok(path: str, text: str) -> tuple[bool, str]:
    """Разбирается ли текст как исходный код. Для не-Python всегда «да».

    Это не проверка правильности правки, а проверка того, что файл
    вообще остался файлом. Стоит доли миллисекунды и ловит самую частую
    поломку слабой модели — потерянную скобку или сбитый отступ.
    """
    if not path.endswith(".py"):
        return True, ""
    try:
        compile(text, path, "exec")
    except SyntaxError as exc:
        return False, f"строка {exc.lineno}: {exc.msg}"
    except ValueError as exc:
        # Нулевой байт внутри исходника: compile() бросает не SyntaxError.
        return False, str(exc)
    return True, ""


def definitions(path: str, text: str) -> set[str]:
    """Имена всех функций и классов файла, включая вложенные.

    Через разбор кода, а не поиском по словам: строка `def` встречается
    и в комментарии, и внутри текстовой константы, а нам нужны настоящие
    определения.
    """
    if not path.endswith(".py"):
        return set()
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return set()
    return {
        node.name
        for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
    }


def filled_bodies(path: str, text: str) -> list[str]:
    """Имена функций, у которых тело — настоящий код, а не пустое место.

    Пустым считается тело из описания в тройных кавычках, `...` и `pass`
    в любом сочетании. Всё остальное — код.

    Нужно там, где просили КАРКАС: проверить это поиском по словам
    нельзя, потому что `...` встречается и внутри описаний, а `pass`
    бывает законной частью настоящей функции. Разбор кода отвечает
    на вопрос прямо.
    """
    if not path.endswith(".py"):
        return []
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return []

    filled = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for statement in node.body:
            if isinstance(statement, ast.Pass):
                continue
            if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant):
                # Описание в тройных кавычках или одинокое `...`.
                if isinstance(statement.value.value, str) or statement.value.value is Ellipsis:
                    continue
            filled.append(node.name)
            break
    return filled


def stray_definitions(path: str, before: str, after: str) -> list[str]:
    """Новые определения, которые правка засунула внутрь чужого блока.

    Живой прогон: на «добавь вывод производной» модель ответила формой
    `append`, а тело начала с четырёх пробелов — и `def` приехал внутрь
    блока `except`, стоявшего в конце файла. Файл разбирается, проверка
    импортом проходит, агент рапортует «Готово». А функция объявляется
    только при ошибке ввода и не вызывается никогда: работы нет, есть
    её видимость.

    Определение внутри `def` или `class` — законное дело: это замыкание
    или метод. Внутри `if`, `try`, `for`, `while`, `with` — почти всегда
    промах отступа, и уж точно промах, когда его туда ДОПИСАЛИ.

    Сравнение с `before` обязательно: в чужом коде такие определения
    могли лежать и до нас, и отменять из-за них правку значит запретить
    трогать файл, который мы не писали.
    """
    if not path.endswith(".py") or not before.strip():
        return []
    return _stray_names(before, after)


def _stray_names(before: str, after: str) -> list[str]:
    """То же самое, но без разговоров про имя файла. Для внутренних проверок."""
    try:
        old = ast.parse(before)
        new = ast.parse(after)
    except (SyntaxError, ValueError):
        return []

    known = _nested_names(old)
    return [name for name in _nested_names(new) if name not in known]


def _nested_names(tree: ast.AST) -> list[str]:
    """Имена определений, лежащих внутри блока, который не def и не class."""
    found: list[str] = []

    def walk(node: ast.AST, inside_block: bool) -> None:
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                if inside_block:
                    found.append(child.name)
                walk(child, False)
            else:
                walk(child, inside_block or isinstance(
                    child, (ast.If, ast.Try, ast.For, ast.AsyncFor, ast.While, ast.With, ast.AsyncWith)
                ))

    walk(tree, False)
    return found


def same_code(before: str, after: str) -> bool:
    """Отличаются ли два текста чем-нибудь, кроме пустых строк.

    Нужно, чтобы отличить правку от её видимости. Живой прогон на задаче
    «исправь NameError: name 'x' is not defined» три раза подряд дал
    ответ, в котором якорь заменялся сам на себя плюс перевод строки:
    файл менялся, инструмент честно отвечал «заменено одно вхождение»,
    шаг засчитывался — и агент рапортовал «Готово» об ошибке, которая
    никуда не делась. Пустая правка хуже отказа: отказ виден.

    Сравнение НЕ трогает отступы слева. Сбитый отступ в Python — самая
    настоящая ошибка, и правка, которая только его и чинит, обязана
    считаться работой. Убираются пустые строки и хвостовые пробелы,
    то есть ровно то, чем ответ модели отличался от исходного файла.
    """
    def bare(text: str) -> list[str]:
        return [line.rstrip() for line in text.splitlines() if line.strip()]

    return bare(before) == bare(after)


def without_docstring(path: str, text: str) -> list[str]:
    """Имена функций без описания в тройных кавычках.

    Пара к `filled_bodies`, и нужна ровно там же. Каркас без описаний —
    это список пустых определений: он разбирается, импортируется
    и не значит ничего. Смысл каркаса в том, что в теле стоит фраза,
    по которой код допишут потом, — своей рукой или вторым проходом
    модели. Проверять надо оба условия: тела пустые И описания есть.
    """
    if not path.endswith(".py"):
        return []
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return []
    return [
        node.name
        for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        and not ast.get_docstring(node)
    ]


def lost_definitions(path: str, before: str, after: str) -> list[str]:
    """Функции и классы, которые правка удалила.

    Проверка появилась из замера, и она закрывает СРАЗУ ДВА способа
    испортить файл, у которых снаружи ничего общего.

    Первый — форма `full`. Модель, которой велели поправить одну функцию
    в файле из десяти, возвращает эту одну функцию как «новое содержимое
    файла». Остальные девять исчезают.

    Второй — форма `lines` на файле длиннее десятка строк. Модель
    ошибается в номере строки на единицу: вместо тела функции заменяет
    её заголовок. Файл при этом остаётся синтаксически целым — просто
    определения в нём больше нет.

    Обе поломки выглядят по-разному, а результат один: из файла пропало
    определение, которого никто не просил трогать. Отсюда и общая
    проверка вместо двух частных.

    Плата названа честно: агент, который ДОЛЖЕН удалить функцию, этой
    проверкой останавливается тоже. Для учебного кодинг-агента на 3B
    такой обмен выгоден — рефакторинг с удалением он всё равно не тянет,
    а терять чужой код при однострочной правке будет постоянно.
    """
    if not path.endswith(".py"):
        return []
    was, became = definitions(path, before), definitions(path, after)
    return sorted(was - became)


def unified(before: str, after: str, path: str, context: int = 3) -> str:
    """Изменения в привычном виде diff — то, что показывают человеку.

    Подтверждение имеет смысл, только если видно, ЧТО подтверждаешь.
    Строка «агент хочет записать agent.py» не даёт человеку ничего;
    четыре строки diff — дают.
    """
    diff = difflib.unified_diff(
        before.splitlines(),
        after.splitlines(),
        fromfile=f"{path} (было)",
        tofile=f"{path} (станет)",
        lineterm="",
        n=context,
    )
    return "\n".join(diff)


# Какие поля нужны каждой форме сверх `form` и `path`.
FIELD_TYPES = {
    ANCHOR: {"old": "string", "new": "string"},
    LINES: {"start": "integer", "end": "integer", "content": "string"},
    FULL: {"content": "string"},
    APPEND: {"content": "string"},
}

# Какие поля нужны каждой форме сверх `form` и `path`, только именами.
REQUIRED_FIELDS = {form: tuple(fields) for form, fields in FIELD_TYPES.items()}


# Отказ, по которому конвейер узнаёт: модель не смогла процитировать
# строку. Константой, а не строкой в двух местах: проверка совпадения
# текста — ровно тот способ ошибиться, на котором глава уже обжигалась.
ANCHOR_MISSED = "Якорь в файле не найден"


def edit_schema(forms: tuple[str, ...] | None = None) -> dict:
    """JSON Schema одной правки — уезжает в Ollama параметром `format`.

    Схема собрана из ТРЁХ вариантов через `oneOf`, по одному на форму,
    и в каждом варианте обязательны все его поля. Первая версия была
    проще: один объект, где обязательны только `form` и `path`,
    а остальные поля опциональны. Рассуждение было такое: объявить
    `start` обязательным нельзя, иначе грамматика заставит заполнять
    его и при правке по якорю.

    Рассуждение верное, вывод неверный, и замер это показал числом.
    Сборка `qwen2_5coder3b_q5` дала 0 применимых правок из 5, и вот её
    типичный ответ:

        {"form": "anchor", "path": "calc.py", "old": "...", "start": 1}

    Форму она называет одну, а поля заполняет от другой: `enum` держит
    значение поля `form`, но ничем не связывает его с набором остальных
    полей. Модель без instruct-тюнинга эту связь и не улавливает —
    в промпте она есть, в грамматике её нет.

    `oneOf` эту связь в грамматику вносит: выбрал `anchor` — обязан дать
    `old` и `new`, и `start` в этом варианте просто не существует.
    Та же модель на той же задаче начинает отвечать применимой правкой.

    Мораль шире одной схемы: **`enum` ограничивает значение поля,
    а не смысл ответа.** Связь между полями надо выражать структурой
    схемы, иначе её приходится проверять после — и на слабой модели
    проверка срабатывает постоянно.

    `missing_fields()` при этом остался. Не как страховка «на всякий
    случай»: план и правку разбирают одним и тем же кодом, а план
    приходит и от человека, и из чекпоинта, где никакой грамматики
    не было.

    `forms` сужает выбор до перечисленных — оставляет только их
    варианты. В работе агента не нужно, там модель выбирает сама;
    нужно замеру, который сравнивает формы между собой. Сравнить их
    иначе нельзя: пока выбор за моделью, мы меряем её предпочтения,
    а не пригодность форм.
    """
    allowed = [form for form in EDIT_FORMS if not forms or form in forms] or list(EDIT_FORMS)
    variants = [_form_variant(form) for form in allowed]
    # Один вариант — `oneOf` из одного элемента лишний: он ничего
    # не выбирает и только мешает читать схему в отладке.
    return variants[0] if len(variants) == 1 else {"oneOf": variants}


def _form_variant(form: str) -> dict:
    """Схема одной формы: её поля обязательны все до единого."""
    properties = {"form": {"type": "string", "enum": [form]}, "path": {"type": "string"}}
    for name, kind in FIELD_TYPES[form].items():
        properties[name] = {"type": kind}
    return {
        "type": "object",
        "properties": properties,
        "required": ["form", "path", *FIELD_TYPES[form]],
    }


def missing_fields(data: dict) -> list[str]:
    """Каких полей не хватает ответу модели для выбранной ею формы.

    Пустая строка считается отсутствующим значением — кроме `new`
    и `content`: пустая замена это законная правка, ею удаляют код.
    """
    form = str(data.get("form", "")).strip()
    if form not in REQUIRED_FIELDS:
        return [f"неизвестная форма правки: {form!r}"]

    missing = []
    for name in REQUIRED_FIELDS[form]:
        value = data.get(name)
        if value is None or (name not in ("new", "content") and str(value).strip() == ""):
            missing.append(name)
    return missing


def describe_forms() -> str:
    """Описание трёх форм для системного промпта.

    Собирается функцией, а не лежит константой, по той же причине, что
    и описание инструментов в Главе 2: список форм — источник истины,
    и текст промпта должен идти за ним, а не жить своей жизнью.
    """
    return "\n".join(
        [
            f"- {ANCHOR}: заменить единственное вхождение фрагмента. Поля: path, old, new.",
            f"- {LINES}: заменить строки по адресу «файл:строки» из поиска. Поля: path, start, end, content.",
            f"- {FULL}: перезаписать файл целиком. Поля: path, content. Только для коротких файлов.",
            f"- {APPEND}: дописать в конец файла. Поля: path, content. Ничего не удаляет.",
        ]
    )
