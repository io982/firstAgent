# Расширения, по которым слово в задаче считается именем файла.
# Список закрыт намеренно: без него именем файла становится любое
# слово с точкой, включая «т.е.» и конец предложения.
CODE_SUFFIXES = (
    ".py", ".txt", ".md", ".json", ".toml", ".cfg", ".ini", ".yml", ".yaml",
    ".bat", ".cmd", ".sh", ".ps1",
)

# Суффиксы, среди которых ищут «последний, над чем работали». Уже, чем
# CODE_SUFFIXES, и намеренно: писать агент умеет и в README, и в .json,
# но «исправь: оно не должно закрываться» — это про работающую
# программу, а не про заметки рядом с ней. Широкий список выбирал бы
# адресом свежий SKILL.md, тронутый совсем по другому поводу.
RUNNABLE_SUFFIXES = (".py", ".bat", ".cmd", ".sh", ".ps1")

# Слова, которыми называют ВИД файла, не называя его имени: «сделай
# батник», «нужен yaml». Нужны для одного вопроса — назван ли в задаче
# целевой файл или только соседний, на который она ссылается.
KIND_WORDS = {
    "bat": ".bat", "cmd": ".cmd",
    "sh": ".sh", "bash": ".sh", "shell": ".sh",
    "ps1": ".ps1", "powershell": ".ps1",
    "json": ".json", "yaml": ".yaml", "yml": ".yaml", "toml": ".toml",
    "markdown": ".md", "readme": ".md",
}

# Русские названия тех же видов — ОСНОВАМИ, как маркеры задач.
# Словарём по целым словам их не покрыть: человек пишет и «батник»,
# и «батника», и «бат файл», и каждое пропущенное написание уводит
# правку в другой файл. Живой прогон споткнулся ровно об это:
# «исправь бат файл в проекте» дало план про quadratic.py.
KIND_STEMS = (
    ("батник", ".bat"), ("бат", ".bat"),
    ("шелл", ".sh"), ("повершелл", ".ps1"),
    ("джейсон", ".json"), ("ямл", ".yaml"),
    ("ридми", ".md"), ("разметк", ".md"),
)


def kind_of_word(word: str) -> str:
    """Вид файла по одному слову задачи. Пусто — слово не про вид."""
    if word in KIND_WORDS:
        return KIND_WORDS[word]
    for stem, suffix in KIND_STEMS:
        if word.startswith(stem):
            return suffix
    return ""

