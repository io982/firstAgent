"""
Память сессии кодинг-агента: что он помнит между запусками.

Хранилище — то же самое, что в Главе 3 (`LongTermMemory`), и это
не экономия усилий, а способ показать, что механизм главы про контекст
работает не только на фактах о человеке. Там агент запоминал «меня
зовут Владимир»; здесь — «мы работаем вот в этом каталоге и правим
вот этот файл». Разница только в том, ЧТО кладут в те же ключи.

Зачем это кодинг-агенту, видно из живых прогонов. Каждый начинался
одинаково: человек набирал `каталог E:\\progects\\CodeAgentTests`,
потому что агент про свой каталог не помнил ничего. А дальше шли
задачи вроде «добавь ожидание ввода» — без имени файла, потому что
человек имел в виду тот файл, который они только что писали вместе,
и считал это очевидным. Оно и очевидно — для того, у кого есть память.

Что помнится и почему именно это:

  * **рабочий каталог** — единственная настройка, которую человек
    вводит руками каждый раз; всё остальное берётся из окружения;
  * **файл, над которым работаем** — адрес правки, когда его не назвали;
  * **последняя задача** — чтобы «а теперь то же самое, но...» имело
    к чему относиться, и чтобы человек видел, на чём остановился.

Первое — одно на агента, остальные два — СВОИ В КАЖДОМ каталоге, и это
не мелочь. Пока все три ключа были общими, работа в двух проектах
подряд молча затирала память первого: возвращаясь к нему, человек
заставал там файл и задачу из чужого проекта. Каталог в такой паре
особый: он отвечает на вопрос «где мы работали в прошлый раз», и
второго ответа у этого вопроса нет.

Чего здесь НЕТ намеренно: истории разговора и содержимого файлов.
Первое живёт в диалогах Главы 3 и стирается командой «забудь»,
второе читается с диска и устаревает в ту же секунду, как его
записали. Память — про адреса, а не про содержимое.
"""

from __future__ import annotations

import hashlib
import os
from pathlib import Path

from chapter3.src.memory import LongTermMemory
from chapter8.src import guard

# Файл памяти лежит рядом с главой, а не в рабочем каталоге агента.
# Это важно: рабочий каталог агент меняет по команде человека, и память,
# лежащая внутри него, при первой же смене каталога стала бы другой
# памятью. Заодно чужой проект не засоряется служебным файлом.
DEFAULT_STATE_PATH = Path(__file__).parent.parent / "session.json"


def state_path() -> Path:
    """Где лежит память сессии. Переменная окружения сильнее умолчания.

    Переменная нужна не для гибкости, а для честности проверок. Память —
    состояние ГЛОБАЛЬНОЕ: планировщик спрашивает её, не получая
    параметром, и без подмены пути тест читал бы файл разработчика.
    Тогда `test_без_цитаты_берётся_последний_изменённый` начинал бы
    падать в зависимости от того, чем человек занимался в агенте вчера,
    — а тест, зависящий от вчерашнего дня, ничего не проверяет.
    """
    return Path(os.environ.get("AGENT_SESSION_FILE") or DEFAULT_STATE_PATH)


WORKSPACE = "workspace"
CURRENT_FILE = "current_file"
LAST_TASK = "last_task"

# Порядок для отчёта — он же порядок, в котором это интересно человеку.
KEYS = (WORKSPACE, CURRENT_FILE, LAST_TASK)

# Ключи, у которых своё значение В КАЖДОМ каталоге.
#
# Рабочий каталог — один на агента: он отвечает на вопрос «где мы
# работали в прошлый раз», и второго ответа тут быть не может. А файл
# и задача принадлежат ПРОЕКТУ: человек, переключившийся с одного
# проекта на другой и вернувшийся обратно, ожидает застать там то,
# на чём остановился. Пока ключи были общими, второй проект молча
# затирал память первого.
PER_WORKSPACE = (CURRENT_FILE, LAST_TASK)


def scope(root: Path | str | None = None) -> str:
    """Как каталог называется внутри ключа памяти: имя плюс отпечаток пути.

    Целым путём было бы читаемее, и первая версия так и делала — пока
    не выяснилось, что ключи памяти Главы 3 НОРМАЛИЗУЮТСЯ: точки,
    дефисы, косые и пробелы там превращаются в подчёркивание
    (`normalize_key`). После такой нормализации `~/my-app` и `~/my_app`
    становятся одним ключом, то есть одной памятью на два разных
    проекта — ровно та беда, от которой ключи и разъезжаются
    по каталогам.

    Поэтому путь превращается в короткий отпечаток, который нормализация
    не трогает: шестнадцатеричные цифры переживают её целиком. Имя
    каталога стоит рядом, чтобы человек, открывший `session.json`,
    видел, о каком проекте речь, а не один голый хэш.

    Регистр снимается только на Windows, и это не придирка:
    `E:\\Progects\\App` и `e:\\progects\\app` там один и тот же каталог,
    а как строки — разные, и памяти вышло бы две.
    """
    path = Path(root or guard.get_workspace()).resolve()
    canonical = path.as_posix()
    if os.name == "nt":
        canonical = canonical.lower()
    fingerprint = hashlib.sha1(canonical.encode("utf-8")).hexdigest()[:8]
    return f"{path.name or 'root'}_{fingerprint}"


TITLES = {
    # Не «рабочий каталог»: тем же словом отчёт о доступе называет ТЕКУЩИЙ
    # каталог, а память хранит тот, где работали в прошлый раз. Совпадают
    # они почти всегда — и именно поэтому один и тот же заголовок на двух
    # разных фактах вводил бы в заблуждение ровно тогда, когда они разошлись.
    WORKSPACE: "Каталог прошлой сессии",
    CURRENT_FILE: "Работаем над файлом",
    LAST_TASK: "Последняя задача",
}


class SessionMemory:
    """Что агент помнит между запусками. Тонкий слой над памятью Главы 3.

    Слой нужен ради одного: ключи здесь СВОИ и заданы списком, а не
    придумываются на ходу. Память Главы 3 принимает любой ключ — она
    для того и сделана, что заранее неизвестно, какие факты человек
    захочет сохранить. Здесь наоборот: фактов ровно три, каждый читает
    определённый кусок кода, и опечатка в ключе означала бы молча
    потерянную настройку.
    """

    def __init__(self, path: Path | str | None = None):
        self._memory = LongTermMemory(path or state_path())
        self._drop_legacy()

    def _drop_legacy(self) -> None:
        """Убирает ключи старого формата — без имени каталога.

        Переносить их некуда: в старом формате нигде не записано,
        к какому проекту относился запомненный файл, и подставить
        его в текущий каталог значило бы вернуть ровно ту беду,
        от которой ключи и разъехались по каталогам.
        """
        for key in PER_WORKSPACE:
            if self._raw(key):
                self._memory.forget(key)

    def _raw(self, key: str) -> str:
        """Значение по точному ключу, без разбора на каталоги."""
        answer = self._memory.recall(key)
        if not answer.startswith("📖"):
            return ""
        return answer.split(" = ", 1)[-1].strip()

    def _key(self, key: str) -> str:
        """Ключ, под которым значение лежит на самом деле."""
        return f"{key}@{scope()}" if key in PER_WORKSPACE else key

    def get(self, key: str) -> str:
        """Значение или пустая строка. Пустая — это «не помню», а не ошибка."""
        return self._raw(self._key(key))

    def set(self, key: str, value: str) -> None:
        """Кладёт значение. Пустое значение стирает ключ, а не пишет пустоту."""
        target = self._key(key)
        if not str(value).strip():
            self._memory.forget(target)
            return
        self._memory.remember(target, str(value).strip())

    def forget_all(self) -> None:
        """Забывает сессию — ТЕКУЩЕГО каталога и общий рабочий каталог.

        Память других проектов остаётся: человек, набравший «забудь
        сессию» в одном проекте, не просил стирать то, на чём он
        остановился в другом.
        """
        for key in KEYS:
            self._memory.forget(self._key(key))

    # ---- то, ради чего всё затевалось -------------------------------

    def restore_workspace(self) -> str:
        """Возвращает агента в каталог прошлой сессии, если он ещё существует.

        Проверка на существование обязательна: каталог могли переименовать
        или удалить между запусками, а `set_workspace` в несуществующий
        путь оставил бы агента без корня — то есть без единственной
        границы, внутри которой ему вообще разрешено писать.

        Переменная окружения СИЛЬНЕЕ памяти. Кто её выставил, сделал это
        только что и осознанно, а память — это то, что было в прошлый раз.
        """
        if os.environ.get("AGENT_WORKSPACE"):
            return ""
        remembered = self.get(WORKSPACE)
        if not remembered or not Path(remembered).is_dir():
            return ""
        guard.set_workspace(remembered)
        return remembered

    def note_workspace(self) -> None:
        """Запоминает текущий каталог. Зовётся после смены каталога."""
        self.set(WORKSPACE, str(guard.get_workspace()))

    def note_work(self, task: str, touched: list[str] | None = None) -> None:
        """Запоминает задачу и файл, над которым работали.

        Файл берётся из ЖУРНАЛА изменений, а не из плана: план говорит,
        что агент собирался сделать, журнал — что вышло. Прогон,
        не тронувший ни одного файла, прошлый адрес не затирает: человек
        после неудачной попытки говорит «ну тогда сделай иначе», имея
        в виду ровно тот же файл.
        """
        self.set(LAST_TASK, task)
        written = touched if touched is not None else [guard.relative(p) for p in guard.changed_files()]
        code = [name for name in written if not name.rsplit("/", 1)[-1].startswith("test_")]
        if code:
            self.set(CURRENT_FILE, code[-1])

    def report(self) -> str:
        """Что агент помнит — человеческими словами."""
        lines = [f"{TITLES[key]}: {self.get(key)}" for key in KEYS if self.get(key)]
        return "\n".join(lines) if lines else "Память сессии пуста."
