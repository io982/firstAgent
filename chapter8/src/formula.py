"""
Формулы: спросить отдельно, проверить вычислением, подложить в правку.

Приём из наблюдения, и наблюдение стоило шести живых прогонов. Модель
на 3B, которую просят «добавь вывод производной», стабильно пишет
в коде `2*a*b - 4*a*c` — дискриминант с перепутанными знаками, выданный
за производную. Выглядело это как потолок модели, и я так и сказал.

Оказалось иначе. Та же модель, спрошенная коротко и отдельно, отвечает
верно, и не через раз, а всегда:

    производная от a*x**2 + b*x + c по x   ->  2*a*x + b
    дискриминант a*x**2 + b*x + c          ->  b**2 - 4*a*c
    площадь круга радиуса r                ->  pi*r**2

Шесть ответов из шести на двух моделях. Знание есть — оно не всплывает
под длинной задачей на написание кода. Это тот же урок, что глава
выучила уже трижды, на форме правки, на имени файла и на выборе места:
**короткий вопрос получает хороший ответ.** Значит, вопрос надо задать
отдельно, а ответ подложить в правку готовым фактом.

Почему ответ ПРОВЕРЯЕТСЯ. `qwen2.5-coder:3b` на площадь круга ответила
`pi * r^2`. На бумаге верно, как код — сломано: в Python `^` это
исключающее ИЛИ, и `r^2` посчитает не квадрат. Формулу, которая
не вычисляется, подкладывать нельзя — это не помощь, а новая беда.
Проверка тут в роли калькулятора: не считать вместо модели,
а проверить то, что она назвала. Стандартной библиотекой, без sympy:
разобрать выражение и вычислить его на пробных числах.
"""

from __future__ import annotations

import ast
import json
import math
import os

from chapter1.agent import request_model
from chapter5.agent import matches

# Спрашивать формулы: "on" — спрашивать, "off" — нет.
#
# ВЫКЛЮЧЕНО по умолчанию, и это решение замера 10, а не осторожность.
# Две задачи по два прогона, формула в коде сверяется с образцом:
#
#     модель                    без справки   со справкой   справка была
#     qwen2.5:3b                        2/4           2/4            0/4
#     qwen2_5coder3b_q5                 4/4           2/4            2/4
#     qwen2.5-coder:3b                  4/4           4/4            2/4
#     qwen2.5-coder:7b                  4/4           2/4            3/4
#     llama3.1:8b                       2/4           2/4            1/4
#
# Справка не помогла НИ РАЗУ, а дважды помешала: 16 верных формул
# из 20 без неё против 12 с ней. И это при том, что сама формула
# добывается верно — короткий вопрос работает, третья колонка
# показывает, что справка доезжала.
#
# Вывод тоньше, чем «приём не работает», и он главный в этом модуле.
# Знание из модели ДОСТАЁТСЯ: спрошенная отдельно, она отвечает
# `2*a*x + b` там, где в коде писала `2*a*b - 4*a*c`. Но пересадить
# добытое знание обратно в длинный запрос не выходит — лишний блок
# в промпте вытесняет внимание с самой задачи. Тот же результат, что
# у замеров 6 и 9: слабой модели не помогает то, что добавляют к её
# запросу; помогает то, что из запроса УБИРАЮТ.
FORMULAS = os.environ.get("AGENT_FORMULAS", "off")

# Слова, за которыми стоит формула. Слева ОСНОВА для поиска, справа
# человеческое слово для вопроса, и разделить их пришлось после живой
# пробы: в вопрос попадала сама основа — «Напиши формулу: производн», —
# и модель, не поняв обрубка, отвечала первым, что похоже на формулу:
# `lambda x: x * math.sin(x) - math.cos(x)`.
#
# Список короткий намеренно. Это не справочник математики — его задача
# заметить, что в задаче есть ВЫЧИСЛЕНИЕ, и спросить о нём. Что именно
# считать, знает модель; наше дело — задать вопрос и проверить ответ.
MATH_WORDS = {
    "производн": "производная",
    "дискриминант": "дискриминант",
    "интеграл": "интеграл",
    "площад": "площадь",
    "объём": "объём",
    "объем": "объём",
    "периметр": "периметр",
    "гипотенуз": "гипотенуза",
    "факториал": "факториал",
    "процент": "процент от числа",
    "средне": "среднее значение",
    "медиан": "медиана",
    "дисперси": "дисперсия",
    "логарифм": "логарифм",
}

# Сколько формул спрашивать за одну задачу. Больше двух — признак того,
# что задача не про вычисление, а про целую библиотеку, и подкладывать
# в правку простыню формул значит вытеснить из окна саму задачу.
MAX_FORMULAS = 2

# Имена, которые разрешено встретить в формуле. Всё остальное — повод
# отказаться: формула должна вычисляться, а не звать что попало.
ALLOWED_NAMES = frozenset({
    "math", "pi", "e", "tau", "inf", "sqrt", "abs", "min", "max", "sum", "pow", "round",
    "sin", "cos", "tan", "log", "log2", "log10", "exp", "floor", "ceil",
    "factorial", "hypot", "degrees", "radians",
})

FORMULA_RULES = """Ты отвечаешь ОДНОЙ формулой и ничем больше.
Кода не пиши, пояснений не давай.

В поле «формула» — выражение на Python через имена переменных из вопроса.
Степень пишется **, а не ^."""


# Примеров функций в правилах НЕТ, и это стоило одного живого прогона.
# Первая версия перечисляла, что можно звать: «Функции — из math без
# приставки: sqrt(d), sin(x), log(n)». На вопрос про производную
# квадратного трёхчлена qwen2.5:3b ответила `math.factorial(x)` —
# взяла функцию из нашего же списка. С правилами без примеров та же
# модель на тот же вопрос отвечает `2*a*x + b`, два раза из двух.
#
# Урок общий и уже знакомый главе с другой стороны: **пример в промпте
# становится ответом.** Планировщику он этим помогал — там пример
# показывал ФОРМУ плана, которую надо повторить. Здесь повторять было
# нечего, и модель повторила единственное, что могла, — имя функции.


def formula_schema() -> dict:
    """Схема ответа: одно поле, и то выражение.

    Самая маленькая работа, какую можно поручить модели, — и потому
    единственная, которую она делает надёжно. Та же схема по существу,
    что у имени файла в планировщике.
    """
    return {
        "type": "object",
        "properties": {"формула": {"type": "string"}},
        "required": ["формула"],
    }


def needs_formulas(task: str) -> list[str]:
    """Какие вычисления упомянуты в задаче. Пусто — спрашивать не о чем."""
    lowered = f" {task.lower().strip()} "
    found = [term for stem, term in MATH_WORDS.items() if matches(lowered, (stem,))]
    return list(dict.fromkeys(found))[:MAX_FORMULAS]


def usable(expression: str) -> tuple[bool, str]:
    """Вычисляется ли формула на пробных числах. Пара «годится, что не так».

    Проверка в роли калькулятора: не посчитать вместо модели, а проверить
    то, что она назвала. Три вопроса по порядку:

      1. разбирается ли это как ВЫРАЖЕНИЕ (не присваивание, не код);
      2. нет ли в нём `^` — на бумаге это степень, в Python исключающее
         ИЛИ, и `r^2` посчитает не квадрат. Живой ответ модели;
      3. считается ли оно на пробных числах и выходит ли число.
    """
    text = (expression or "").strip()
    if not text:
        return False, "формула пустая"
    if "^" in text:
        return False, "в формуле знак ^ — в Python это исключающее ИЛИ, степень пишется **"
    try:
        tree = ast.parse(text, mode="eval")
    except (SyntaxError, ValueError) as exc:
        return False, f"формула не разбирается как выражение: {exc}"

    names = {node.id for node in ast.walk(tree) if isinstance(node, ast.Name)}
    unknown = sorted(name for name in names if name not in ALLOWED_NAMES and len(name) > 2)
    if unknown:
        return False, f"в формуле незнакомые имена: {', '.join(unknown)}"

    # Пробные значения: единица всем переменным. Ноль не годится —
    # деление на переменную встречается в формулах постоянно.
    space = {name: 1.0 for name in names}
    space.update({name: getattr(math, name) for name in ALLOWED_NAMES if hasattr(math, name)})
    space.update({"abs": abs, "min": min, "max": max, "sum": sum, "pow": pow, "round": round})
    # `math.sqrt(d)` модель пишет охотнее, чем `sqrt(d)`, — и правильно
    # делает: именно так это выглядит в коде, который она правит.
    space["math"] = math
    try:
        value = eval(compile(tree, "<формула>", "eval"), {"__builtins__": {}}, space)  # noqa: S307
    except Exception as exc:  # noqa: BLE001
        return False, f"формула не считается: {exc}"
    if not isinstance(value, (int, float, complex)):
        return False, f"формула дала не число, а {type(value).__name__}"
    return True, ""


EXPRESSION_RULES = """Ты отвечаешь ОДНИМ выражением, которое считает этот код.

Правила:
1. В поле «формула» — математическое выражение на Python через имена
   переменных из кода: a, b, c, x, r, n.
2. Не пересказывай код и не пиши функцию — только само выражение.
3. Если код считает корни уравнения, напиши само уравнение: a*x**2 + b*x + c."""


def ask_expression(source: str, model_call=None) -> str:
    """Спрашивает, какое ВЫРАЖЕНИЕ считает этот код.

    Половина двухшагового вопроса. «Производная» без предмета — вопрос
    без ответа, а предмет надо откуда-то взять: в задаче его нет,
    в коде он есть, но не выписан. Сначала спрашиваем выражение,
    потом формулу от него — оба вопроса короткие, и оба того вида,
    на котором 3B держится.
    """
    if not source.strip():
        return ""
    ask = model_call or request_model
    messages = [
        {"role": "system", "content": EXPRESSION_RULES},
        {"role": "user", "content": f"Код:\n{source.strip()}"},
    ]
    try:
        answer = json.loads(ask(messages, response_format=formula_schema()))
    except Exception:  # noqa: BLE001
        return ""
    expression = str(answer.get("формула", "")).strip()
    return expression if usable(expression)[0] else ""


def ask_formula(question: str, model_call=None) -> str:
    """Спрашивает у модели одну формулу. Пусто — не спросили или не годится.

    Вопрос приходит готовым и КОРОТКИМ, без кода. Это выяснилось живой
    пробой, и результат ровно обратный ожиданию. Чистый вопрос
    «производная от a*x**2 + b*x + c по x» даёт `2*a*x + b` — верно,
    шесть раз из шести. Тот же вопрос с приложенным исходником функции
    даёт `2*a`. Код в запросе восстанавливает то самое длинное задание,
    из-под которого знание и не всплывает.

    Отсюда двухшаговость: предмет достаётся из кода отдельным вопросом
    (`ask_expression`), а формула спрашивается уже про предмет, и кода
    в этом запросе нет.

    Проверенный ответ или ничего. Формула, которая не вычисляется,
    хуже отсутствующей: отсутствие модель заметит сама, а неверную
    подсказку примет за факт.
    """
    ask = model_call or request_model
    messages = [
        {"role": "system", "content": FORMULA_RULES},
        {"role": "user", "content": question},
    ]
    try:
        answer = json.loads(ask(messages, response_format=formula_schema()))
    except Exception:  # noqa: BLE001
        return ""
    expression = str(answer.get("формула", "")).strip()
    return expression if usable(expression)[0] else ""


def question_for(term: str, expression: str, task: str) -> str:
    """Собирает короткий вопрос о формуле. Кода в нём нет намеренно.

    Предмет берётся из выражения, если его удалось достать из кода:
    «производная от a*x**2 + b*x + c по x». Не удалось — спрашиваем
    по задаче, но всё равно одной строкой.
    """
    if expression:
        return f"{term} от {expression} по x"
    return f"{term}, о которой просит задача: {task.strip()}"


def hints(task: str, source: str = "", model_call=None) -> str:
    """Справка с формулами для запроса правки. Пусто — вычислений в задаче нет."""
    if FORMULAS != "on":
        return ""
    terms = needs_formulas(task)
    if not terms:
        return ""

    # Предмет достаётся ОДИН раз на все формулы: вопрос про код у нас
    # один и тот же, а лишний запрос к 3B — это секунды.
    expression = ask_expression(source, model_call) if source else ""

    lines = []
    for term in terms:
        formula = ask_formula(question_for(term, expression, task), model_call)
        if formula:
            lines.append(f"- {term}: {formula}")
    if not lines:
        return ""
    head = "СПРАВКА, формулы для этой задачи (спрошены отдельно и проверены вычислением):"
    return head + "\n" + "\n".join(lines) + "\n\n"
