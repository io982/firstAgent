"""
Конвейер работы: план — подтверждение — шаги — зависимости — проверка (8.4).

Здесь заканчивается свобода агента и начинается программа. Глава 7
показала, что бывает, когда маршрут выбирает код, а не модель;
эта глава доводит мысль до конца: в работе над кодом маршрут известен
заранее целиком.

    план -> подтверждение -> шаг ⟲ (пока шаги не кончились)
                              |
                              v
                        зависимости -> проверка
                                        ↙      ↘ провал
                                    готово   прочитать -> изменить
                                                 ^            |
                                                 +------------+
                                        попытки исчерпаны -> откат

Почему это записано графом, а не десятком вызовов подряд. Из-за двух
стрелок, идущих назад: цикла по шагам плана и цикла починки. Обе
выражаются условным ребром в одну строку, которое можно прочитать
глазами и покрыть тестом; последовательность вызовов выражает их
вложенными циклами и флагами.

Куда ведёт стрелка починки — не мелочь. Она ведёт к ЧТЕНИЮ, а не сразу
к правке, и первая версия конвейера вела её к правке. Разница вылезла
на живой модели: после неудачной попытки файл на диске уже другой,
а в контексте у модели лежал текст, прочитанный до правки. Ей показывали
исходный файл и говорили «тесты не прошли» — и она уверенно повторяла
ту же правку, которая теперь отвергалась как «текст совпадает с прежним».
Круг сгорал впустую. Читаем заново — модель видит, что натворила.

Четыре решения, которые стоит назвать вслух.

**Модель зовётся в двух узлах** — когда надо написать файл (`step`
с действием create) и когда надо его починить (`edit`). Всё остальное —
поиск, чтение, установка пакетов, запуск тестов, разбор их вывода —
делает код. Чем меньше мест, где решает 3B, тем меньше мест, где всё
разваливается.

**Подтверждение стоит до первого действия, а не перед каждым.** Человек
смотрит план целиком и говорит «да» один раз. Дальше вопрос задаётся
только там, где меняется диск или запускается команда, — это работа
`guard`, и она никуда не девается.

**Зависимости — узел графа, а не шаг плана.** Какие пакеты нужны, это
не мнение модели, а факт: разобрать импорты написанного кода и спросить
у интерпретатора, чего не хватает. Модель, которую спрашивают о том,
что можно вычислить, отвечает правдоподобно и неверно.

**Провал по исчерпании попыток — это откат, а не «как-нибудь оставим».**
Файлы возвращаются в состояние до прогона. Наполовину сделанная работа
хуже несделанной: она выглядит как сделанная.
"""
