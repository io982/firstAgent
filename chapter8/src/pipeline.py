def importable(name: str) -> bool:
    """Годится ли строка как имя модуля в `import ...`.

    Точки разрешены (`os.path`), ключевые слова языка — нет: `import
    assert` не разбирается, а именно это модель однажды и предложила.
    """
    parts = name.split(".")
    return bool(name) and all(p.isidentifier() and not keyword.iskeyword(p) for p in parts)


def render_skeleton(spec: dict, task: str) -> str:
    """Собирает скелет файла из состава. Модели здесь нет — только код.

    Именно этот шаг делает приём осмысленным. Скелет — не «черновик
    от модели», а форма, выведенная кодом из её короткого ответа:
    порядок определений, отступы, кавычки описаний и точка входа
    расставлены нами и одинаковы всегда. Модели остаётся ровно то,
    что она умеет, — дописать тела.
    """
    lines: list[str] = [f'"""{task.strip()}"""']

    # Имя модуля проверяется, а не подставляется как есть. Живой замер
    # показал цену доверия: на задаче про самое длинное слово модель
    # перечислила в `imports` слово `assert`, скелет получил строку
    # `import assert` и не разобрался — весь прогон кончился ничем
    # из-за одного слова в списке. Модель отвечает про смысл, а
    # синтаксис — наша забота.
    imports = [name for name in dict.fromkeys(str(n).strip() for n in spec.get("imports", [])) if importable(name)]
    if imports:
        lines.append("")
        lines.extend(f"import {name}" for name in imports)

    for item in spec.get("functions", []):
        name = str(item.get("name", "")).strip()
        if not name.isidentifier():
            continue
        args = ", ".join(a.strip() for a in str(item.get("args", "")).split(",") if a.strip())
        purpose = str(item.get("purpose", "")).strip().replace('"""', "'")
        lines.extend(["", "", f"def {name}({args}):", f'    """{purpose}"""', "    ..."])

    # Точка входа: названная моделью или, если она промолчала, функция
    # с именем `main`. Запасной вариант нужен — живой прогон показал,
    # что поле `entry` модель заполняет через раз, и без него готовый
    # файл оставался без блока `if __name__`, то есть не запускался.
    known = {str(f.get("name", "")).strip() for f in spec.get("functions", [])}
    entry = str(spec.get("entry", "")).strip()
    if entry not in known:
        entry = "main" if "main" in known else ""
    if entry:
        lines.extend(["", "", 'if __name__ == "__main__":', f"    {entry}()"])

    return "\n".join(lines) + "\n"


def coder_model() -> str:
    """Какая модель пишет код. Пусто в переменной — та же, что у курса."""
    return CODER_MODEL or base.MODEL


def file_schema() -> dict:
    """Схема ответа на «напиши файл»: одно поле, и то содержимое.

    Пути в схеме НЕТ намеренно. Путь известен из шага плана, который
    человек уже подтвердил, и спрашивать его у модели значит открывать
    ей возможность записать не туда. Поле, которого нет в схеме,
    заполнить нельзя.
    """
    return {
        "type": "object",
        "properties": {"content": {"type": "string"}},
        "required": ["content"],
    }


