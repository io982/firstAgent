#   3. модель дописывает тела — задача на дополнение.
#
# Замер главы (TestWriteMode), пять задач с нуля по два прогона.
# «Не написан» — прогоны, где файл не дошёл до диска вовсе:
#
#     модель                     direct  не написан   skeleton  не написан
#     qwen2.5:3b                   4/10        4/10       4/10        6/10
#     qwen2_5coder3b_q5 (базовая)  7/10        0/10       2/10        6/10
#     qwen2.5-coder:3b             9/10        0/10       9/10        1/10
#     qwen2.5-coder:7b            10/10        0/10       9/10        0/10
#     llama3.1:8b                  7/10        1/10       4/10        4/10
#
