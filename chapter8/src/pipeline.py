def node_plan(state: State) -> State:
    """Составляет план — или берёт готовый, если его положили заранее.

    Готовый план кладут два вызывающих: человек, поправивший шаги
    руками, и чекпоинт, поднявший прогон с середины. Оба случая
    выглядят одинаково, поэтому и обрабатываются одинаково.
    """
    if "plan" not in state.extra:
        plan = make_plan(state.user_input)
        state.extra["plan"] = plan.to_dict()
    plan = Plan.from_dict(state.extra["plan"])
    state.extra["plan_problems"] = validate_plan(plan)
    state.extra.setdefault("cursor", 0)
    state.extra.setdefault("attempt", 0)
    state.extra.setdefault("log", [])
    state.extra.setdefault("touched", [])
    state.extra.setdefault("failed_steps", [])
    # Обещал ли план НАПИСАТЬ тесты. Обещание запоминается здесь,
    # а спрашивается в узле проверки: план, обещавший тесты и не
    # создавший их, — это провал, а не повод проверить чем-нибудь другим.
    #
    # Считается только шаг `create` с именем `test_*`, и это уточнение
    # стоило одного упавшего прогона. Первая версия засчитывала сюда
    # и шаг `test`, но `test` означает «проверь», а не «напиши тесты»:
    # промпт планировщика требует ставить его последним ВСЕГДА, и любая
    # задача вроде «напиши hello world» после этого объявлялась
    # провалившейся за отсутствие тестов, которых никто не просил.
    state.extra["wants_tests"] = any(
        step.action == CREATE and step.target.rsplit("/", 1)[-1].startswith("test_")
        for step in plan.steps
    )
    return state


def node_confirm(state: State) -> State:
    """Показывает план человеку и спрашивает разрешение — до первого действия.

    Единственный узел, который может остановить прогон по решению
    человека. Ответ кладётся в состояние, а не влияет на поток напрямую:
    поток меняет условное ребро, и это разделение позволяет проверить
    отказ тестом, не подделывая ввод с клавиатуры.
    """
    plan = Plan.from_dict(state.extra.get("plan", {}))
    problems = state.extra.get("plan_problems", [])
    shown = render_plan(plan, problems)
    state.extra["plan_text"] = shown

    if not plan.steps:
        state.extra["approved"] = False
        state.answer = "План пуст — выполнять нечего.\n" + shown
        return state

    verdict = guard.check(f"выполнить план из {len(plan.steps)} шагов", shown)
    state.extra["approved"] = verdict == guard.ALLOW
    if verdict != guard.ALLOW:
        state.answer = guard.verdict_message(verdict, "выполнить план")
    return state


def node_step(state: State) -> State:
    """Выполняет ОДИН шаг плана и сдвигает курсор.

    Один шаг за посещение узла — потому что между шагами должно быть
    место для решения «идти дальше или хватит». Цикл, спрятанный внутри
    узла, такого места не оставляет, и остановить его на середине
    (чекпоинтом, отказом человека, пределом шагов) уже нечем.
    """
    plan = Plan.from_dict(state.extra.get("plan", {}))
    cursor = int(state.extra.get("cursor", 0))
    if cursor >= len(plan.steps):
        return state

    step = plan.steps[cursor]
    state.extra["cursor"] = cursor + 1
    ok, result = _run_step(step, state)

    mark = "" if ok else "  ← ПРОВАЛ"
    state.extra.setdefault("log", []).append(
        f"{cursor + 1}. {step.action} {step.target} — {result}{mark}"
    )
    if not ok:
        # Провалившиеся шаги копятся, а прогон продолжается: следующий
        # шаг может и получиться. Но итог о них ОБЯЗАН сказать — иначе
        # агент отчитается «Готово» по половине сделанной работы.
        # Именно это и случилось на живом прогоне.
        state.extra.setdefault("failed_steps", []).append(f"{cursor + 1}. {step.action} {step.target}")
    return state


def _run_step(step, state: State) -> tuple[bool, str]:
    """Диспетчер шагов. Одна функция на все действия — как execute_tool Главы 2.

    Одна, а не шесть узлов графа, по той же причине, по какой в Главе 2
    один диспетчер на шестнадцать инструментов: граф описывает ПОРЯДОК
    работы, а какое именно действие выполняется на шаге — это данные,
    а не структура. Шесть узлов пришлось бы связать двадцатью рёбрами,
    и читать граф стало бы нельзя.

    Возвращает ПАРУ «получилось, отчёт», а не одну строку. Разница
    та же, что уже дважды выручала в этой главе: успех шага — это факт,
    а не слово в тексте сообщения. Первая версия возвращала строку,
    и провалившийся шаг отличался от удавшегося только формулировкой,
    которую никто не проверял. Живой прогон это и показал: модель
    не написала второй файл, шаг молча провалился, а агент отчитался
    «Готово».
    """
    handlers = {
        SEARCH: _step_search,
        READ: _step_read,
        CREATE: _step_create,
        EDIT: _step_edit,
        RUN: _step_run,
        TEST: _step_test,
    }
    handler = handlers.get(step.action)
    if handler is None:
        return False, f"действие {step.action!r} выполнять нечем"
    return handler(step, state)


def _step_search(step, state: State) -> tuple[bool, str]:
    """Находит файл: по имени, если это путь, иначе поиском по тексту."""
    target = step.target.strip()
    if not target:
        return False, "нечего искать: пустой запрос"

    # Сначала проверяем, не путь ли это. Шаг `search calc.py` выглядит
    # как поиск, а означает «работай вот с этим файлом», и искать текст
    # «calc.py» ВНУТРИ файлов бессмысленно: в них написано
    # `from calc import add`, и совпадений не будет.
    try:
        named = guard.resolve_path(target)
    except guard.OutsideWorkspace as exc:
        return False, str(exc)
    if named.is_file():
        state.extra["path"] = guard.relative(named)
        return True, f"файл {guard.relative(named)}"

    found = search_files(target, "*.py")
    path = _first_path(found)
    if not path:
        return False, f"по запросу {target!r} ничего не нашлось"
    state.extra["path"] = path
    return True, f"найден {path}"


def _first_path(search_output: str) -> str:
    """Первый путь из выдачи поиска — она отвечает строками «файл:строка: текст»."""
    for line in search_output.splitlines():
        if ":" in line and not line.startswith(("Найдено", "Ничего")):
            return line.split(":", 1)[0].strip()
    return ""


def _step_read(step, state: State) -> tuple[bool, str]:
    """Кладёт файл в состояние — с номерами строк, как их принимает правка."""
    target = step.target.strip() or state.extra.get("path", "")
    if not target:
        return False, "нечего читать: файл не назван"
    text = read_lines(target, "1", str(CONTEXT_LINES))
    if text.startswith("Нет такого файла"):
        return False, text
    state.retrieved = text
    state.extra["path"] = target
    return True, f"прочитан {target}"


def _step_create(step, state: State) -> tuple[bool, str]:
    """Просит модель написать файл целиком и записывает его.

    Порядок кусков в запросе выбран не для красоты. Соседние файлы идут
    ПЕРЕД заданием, а не после, и помечены как справка: живая проба
    показала, что модель, увидевшая соседний файл последним, отвечает
    его содержимым вместо запрошенного. Последнее, что она прочитала, —
    это то, что она напишет, и потому последним должно стоять имя файла,
    который нужен сейчас.

    Соседи нужны всё равно: тест, который агент пишет вторым шагом,
    без них импортирует выдуманные имена — он видел формулировку задачи,
    но не то, что написал первый шаг.

    Попыток две, и это не запас прочности. Файл, который не записался,
    потерян насовсем: цикл починки правит существующие файлы и создать
    недостающий не умеет. Один провалившийся `create` обрушивал весь
    прогон — на живом прогоне модель выдала `def add(a, b):` без тела,
    файл не прошёл разбор, и задача кончилась ничем. Вторая попытка
    отличается от первой тем же, чем в цикле починки: модели говорят,
    что было не так.
    """
    path = step.target.strip()
    if not path:
        return False, "нечего создавать: путь не назван"

    problem = ""
    for attempt in range(1, CREATE_ATTEMPTS + 1):
        ok, result = _write_once(step, state, path, problem, attempt)
        if ok:
            return True, result
        problem = result
    return False, problem


def _write_once(step, state: State, path: str, problem: str, attempt: int) -> tuple[bool, str]:
    """Один заход «напиши файл» и попытка записать ответ.

    Заходов три. Первый выбирает ЗАДАЧА: попросили каркас — каркас
    и есть результат, и второго прохода не будет. Между остальными
    двумя выбирает `WRITE_MODE`: `direct` — один запрос за файлом
    целиком, `skeleton` — сначала состав файла, потом дописывание тел.
    Какой из этих двух лучше на какой модели, говорит замер главы,
    а не рассуждение.
    """
    if wants_scaffold(state.user_input) and path.endswith(".py"):
        content, trouble = _content_scaffold(step, state, path, problem, attempt)
    elif WRITE_MODE == "skeleton" and path.endswith(".py"):
        content, trouble = _content_by_skeleton(step, state, path, problem, attempt)
    else:
        content, trouble = _content_directly(step, state, path, problem, attempt)
    if trouble:
        return False, trouble

    touched = guard.change_count()
    # replace=True: шаг `create` — это прямое «напиши вот этот файл»,
    # подтверждённое человеком по имени. Если файл уже есть, его пишут
    # заново, и пропавшие определения тут не промах, а то, о чём просили.
    result = put_file(path, content, replace=True)
    if guard.change_count() == touched:
        return False, f"{result} (попытка {attempt})"
    _remember(state, path)
    return True, result


def _ask_file(system: str, user: str, schema: dict) -> tuple[dict | str, str]:
    """Один запрос к модели, пишущей код. Возвращает ответ и текст беды.

    Своё время ожидания и предел длины. Написать файл целиком —
    генерация на сотни токенов, и общего предела Главы 1 на неё
    не хватает; а без предела длины генерация иногда уходит в разгон
    и всё равно упирается в таймаут.
    """
    messages = [{"role": "system", "content": system}, {"role": "user", "content": user}]
    try:
        with using_model(coder_model()), _patience(WRITE_TIMEOUT):
            raw = request_model(messages, response_format=schema, options={"num_predict": WRITE_MAX_TOKENS})
        answer = json.loads(raw)
    except Exception as exc:  # noqa: BLE001
        return {}, str(exc)
    # Схема требует объект, но проверка стоит всё равно: разбор JSON
    # возвращает и список, и строку, а вызывающий сразу зовёт `.get()`
    # и падает уже вне обработчика — там, где беду никто не ловит.
    if not isinstance(answer, dict):
        return {}, f"ответ не объект, а {type(answer).__name__}"
    return answer, ""


def _task_block(step, state: State, path: str, problem: str) -> str:
    """Хвост запроса: что за файл нужен и какая задача.

    Задача идёт ПОСЛЕДНЕЙ, и это не оформление. Описание шага стояло
    после неё и читалось как спецификация — а планировщик кладёт туда
    пересказ задачи, который короче её самой. На задаче «калькулятор,
    ждать ввода, парсить» пересказ свёлся к списку арифметических
    функций, и модель написала библиотеку без приложения.
    """
    hint = step.detail.strip()
    text = f"СЕЙЧАС НУЖЕН ОДИН ФАЙЛ: {path}\n"
    # Подсказку показываем, только если она НЕ пересказ той же задачи:
    # план из кода кладёт туда саму задачу, и печатать её дважды значит
    # тратить контекст на повтор.
    if hint and hint != state.user_input.strip():
        text += f"Подсказка из плана (не ограничение, а напоминание): {hint}\n"
    text += f"\nЗАДАЧА ЦЕЛИКОМ — делай ровно её, ничего не упуская:\n{state.user_input}\n"
    if problem:
        text += f"\nПрошлая попытка не годится: {problem}\n"
    return text


def _content_directly(step, state: State, path: str, problem: str, attempt: int) -> tuple[str, str]:
    """Один запрос: модель отдаёт файл целиком."""
    user = (
        f"{_neighbours(state)}{_task_block(step, state, path, problem)}\n"
        f"Верни содержимое файла {path} целиком. Не соседнего, не части — этого и всего."
    )
    answer, trouble = _ask_file(CREATE_RULES, user, file_schema())
    if trouble:
        return "", f"модель не написала файл (попытка {attempt}): {trouble}"

    content = _strip_fences(str(answer.get("content", "")))
    if not content.strip():
        return "", f"модель вернула пустой файл (попытка {attempt})"
    return content, ""


def _content_scaffold(step, state: State, path: str, problem: str, attempt: int) -> tuple[str, str]:
    """Каркас как РЕЗУЛЬТАТ работы: определения с описаниями, тела пустые.

    Это первая половина `_content_by_skeleton`, остановленная на
    полпути, и такое совпадение не случайно: человеку, просящему
    каркас, нужно ровно то, что конвейер строит себе сам, — состав
    файла в виде кода.

    Свободной генерацией это не делается, и проверено живьём. Правила
    «тело — описание в тройных кавычках и многоточие» модель понимает
    наполовину: тела действительно оставляет пустыми, а описания
    не пишет — два захода подряд вернули `pass` без единой фразы.
    Каркас без описаний бесполезен: по нему нечего дописывать.
    Поэтому у модели спрашивают только СОСТАВ — имя, аргументы,
    назначение фразой, — а форму файла собирает `render_skeleton`,
    и описания в ней стоят всегда.

    Проверки на выходе поэтому дешёвые и стоят скорее сторожем:
    сборка кодом не умеет написать тело, но если она изменится,
    молчать об этом не должна.
    """
    user = (
        f"{_neighbours(state)}{_task_block(step, state, path, problem)}\n"
        f"Перечисли, что должно быть в файле {path}. Кода не пиши."
    )
    spec, trouble = _ask_file(SKELETON_RULES, user, file_plan_schema())
    if trouble:
        return "", f"модель не назвала состав файла (попытка {attempt}): {trouble}"

    content = render_skeleton(spec, state.user_input)
    ok, syntax_problem = syntax_ok(path, content)
    if not ok:
        return "", f"каркас не разбирается ({syntax_problem}, попытка {attempt})"
    if not definitions(path, content):
        return "", f"в каркасе нет ни одного определения (попытка {attempt})"
    filled = filled_bodies(path, content)
    if filled:
        return "", f"просили каркас, а тела написаны у функций: {', '.join(filled)} (попытка {attempt})"
    mute = without_docstring(path, content)
    if mute:
        return "", f"в каркасе нет описаний у функций: {', '.join(mute)} (попытка {attempt})"
    return content, ""


def _content_by_skeleton(step, state: State, path: str, problem: str, attempt: int) -> tuple[str, str]:
    """Два запроса: сначала состав файла, потом дописывание тел.

    Приём подстраивается под то, чему модель обучена. Базовая
    Coder-модель — про ДОПОЛНЕНИЕ кода, а не про исполнение инструкций;
    «напиши файл по описанию» — второе, «допиши тела в готовый скелет» —
    первое. Между двумя запросами стоит код: он собирает скелет
    из короткого структурированного ответа, и форма файла оказывается
    не на совести модели.
    """
    user = (
        f"{_neighbours(state)}{_task_block(step, state, path, problem)}\n"
        f"Перечисли, что должно быть в файле {path}. Кода не пиши."
    )
    spec, trouble = _ask_file(SKELETON_RULES, user, file_plan_schema())
    if trouble:
        return "", f"модель не назвала состав файла (попытка {attempt}): {trouble}"

    skeleton = render_skeleton(spec, state.user_input)
    ok, syntax_problem = syntax_ok(path, skeleton)
    if not ok:
        return "", f"скелет не разбирается ({syntax_problem}, попытка {attempt})"
    state.extra["skeleton"] = skeleton

    filled, trouble = _ask_file(
        FILL_RULES,
        f"{_task_block(step, state, path, problem)}\nСкелет файла {path}:\n{skeleton}",
        file_schema(),
    )
    if trouble:
        return "", f"модель не дописала тела (попытка {attempt}): {trouble}"

    content = _strip_fences(str(filled.get("content", "")))
    if not content.strip():
        return "", f"модель вернула пустой файл (попытка {attempt})"

    # Сперва разбор, и только потом сверка состава. Порядок важен для
    # ОТЧЁТА: неразобравшийся файл не имеет определений вовсе, и сверка
    # состава честно объявляет пропавшими все до одной функции. Замер
    # из-за этого показывал «при дописывании пропали функции» там, где
    # на деле модель ушла в разгон — писала assert за assert, пока
    # не упёрлась в предел длины, и ответ оборвался на полуслове.
    # Беда была не в составе, а в длине, и чинить надо было её.
    ok, syntax_problem = syntax_ok(path, content)
    if not ok:
        return "", f"дописанное не разбирается ({syntax_problem}, попытка {attempt})"

    # Скелет — это договор о составе, и дописывание не имеет права его
    # нарушить. Проверка та же, что у правок: пропали определения —
    # значит модель написала не то, что обещала.
    lost = lost_definitions(path, skeleton, content)
    if lost:
        return "", f"при дописывании пропали функции: {', '.join(lost)} (попытка {attempt})"
    return content, ""


@contextmanager
def _patience(seconds: float):
    """Временно поднимает время ожидания ответа модели.

    Подменяется константа Главы 1, потому что через неё ходят все
    запросы курса. Возврат в try/finally: исключение внутри не должно
    оставить курс с чужим таймаутом до конца сессии. Тот же приём,
    что `using_model()` в Главе 7, и по той же причине.
    """
    previous = base.REQUEST_TIMEOUT
    base.REQUEST_TIMEOUT = seconds
    try:
        yield
    finally:
        base.REQUEST_TIMEOUT = previous


def _neighbours(state: State) -> str:
    """Уже написанные файлы — коротко, справкой перед заданием.

    Слово «СПРАВКА» и оговорка «переписывать их не надо» стоят здесь
    не для вежливости: без них модель отвечала содержимым соседнего
    файла вместо запрошенного. Соседний файл — самый длинный кусок
    в запросе, и без явной пометки он читается как образец для ответа.
    """
    touched = state.extra.get("touched", [])
    if not touched:
        return ""
    parts = ["СПРАВКА, уже написанные файлы проекта (переписывать их не надо):"]
    for path in touched[-3:]:
        parts.append(f"--- {path} ---\n{read_lines(path, '1', str(NEIGHBOUR_LINES))}")
    return "\n".join(parts) + "\n\n"


def _strip_fences(text: str) -> str:
    """Снимает ```-обёртку, если модель её всё-таки поставила.

    Правило «без ```» в промпте есть, и модель его нарушает: разметка
    кода блоками встречается в её обучающих данных чаще, чем голый
    исходник. Снять три символа дешевле, чем спорить промптом.
    """
    stripped = text.strip()
    if not stripped.startswith("```"):
        return text
    lines = stripped.splitlines()[1:]
    if lines and lines[-1].strip().startswith("```"):
        lines = lines[:-1]
    return "\n".join(lines) + "\n"


def _remember(state: State, path: str) -> None:
    """Запоминает файл, которого агент коснулся, без повторов."""
    touched = state.extra.setdefault("touched", [])
    if path not in touched:
        touched.append(path)
    state.extra["path"] = path


def _step_edit(step, state: State) -> tuple[bool, str]:
    """Правит существующий файл: читает, спрашивает модель, применяет.

    Попыток две, ровно как у создания файла. Вторая отличается от первой
    тем, что модели говорят, чем не годится первая, — и отказ инструмента
    для этого уже написан подробно: он называет похожую строку из файла,
    когда якорь не найден, и место разбора, когда файл после правки
    перестаёт разбираться. Не передать это обратно значит выбросить
    готовое объяснение и остановить прогон на первой же осечке.
    """
    path = step.target.strip() or state.extra.get("path", "")
    if not path:
        return False, "нечего править: файл не назван"

    state.retrieved = read_lines(path, "1", str(CONTEXT_LINES))
    state.extra["path"] = path

    problem = ""
    for _ in range(EDIT_ATTEMPTS):
        was = _file_text(path)
        touched = guard.change_count()
        result = _ask_for_edit(state, path, step.detail, problem)
        if guard.change_count() == touched:
            problem = result
            continue
        # Файл изменился — но изменился ли КОД. Модель умеет ответить
        # правкой, где якорь заменяется сам на себя плюс пустая строка:
        # инструмент честно пишет «заменено одно вхождение», журнал
        # считает изменение, а ошибка в файле остаётся. Такой ответ
        # засчитывать нельзя, иначе агент рапортует «Готово» о работе,
        # которой не было.
        if same_code(was, _file_text(path)):
            problem = ("правка ничего не изменила в коде — вернулся тот же текст. "
                       "Найди в файле строку, которую задача просит поменять, и поменяй ЕЁ")
            continue
        _remember(state, path)
        return True, result
    return False, problem


def _file_text(path: str) -> str:
    """Текст файла или пустая строка, если его не прочитать.

    Пустая строка вместо исключения намеренно: это чтение для СРАВНЕНИЯ,
    и нечитаемый файл здесь означает «сравнивать не с чем», а не беду.
    """
    try:
        return guard.resolve_path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError, guard.OutsideWorkspace):
        return ""


def _step_test(step, state: State) -> tuple[bool, str]:
    """Запоминает, что проверять. Сам прогон — в узле `verify`.

    Прогон отложен, и не для удобства: проверка должна случиться ОДИН
    раз и в конце, что бы ни стояло в плане. Модель ставит шаг `test`
    и в середину плана, и дважды подряд, а «проверено» — это состояние
    прогона, а не пункт списка.

    Отдельно проверяется, что названный файл существует. Живая модель
    регулярно пишет план из двух шагов — «создай hello.py» и «прогони
    test_hello.py», — забыв создать второй файл. Записать такое имя
    в цель проверки значит запустить pytest по несуществующему пути,
    получить ошибку и отправить агента чинить то, чего он не писал.
    """
    target = step.target.strip()
    if not target:
        return True, "проверка отложена до конца плана"
    try:
        if guard.resolve_path(target).exists():
            state.extra["tests"] = target
            return True, f"проверять будем {target}, прогон в конце"
    except guard.OutsideWorkspace as exc:
        return False, str(exc)
    return True, f"файла {target} нет — проверим тем, что есть"


def _step_run(step, state: State) -> tuple[bool, str]:  # noqa: ARG001
    """Выполняет команду из шага плана — через те же проверки, что и инструмент."""
    # Команда берётся из `target`, а если его нет — из `detail`.
    # Запасной путь появился после живого прогона: план от модели
    # выглядел как «run — python test_calc.py», то есть команда уехала
    # в описание, а поле пути осталось пустым. Отказать в такой ситуации
    # значит потерять шаг из-за того, в какое поле модель положила
    # строку, которую и так видно.
    command = step.target.strip() or step.detail.strip()
    if not command:
        return False, "нечего выполнять: команда не названа"

    allowed, reason = guard.command_allowed(command)
    if not allowed:
        return False, f"команда не выполнена: {reason}"

    # Запуск программы, которая ждёт ввода, — не проверка, а гарантированный
    # EOFError: у прогона нет пользователя, который нажмёт клавиши. Узел
    # проверки это уже знает и импортирует такие файлы вместо запуска;
    # шаг плана `run` знать это обязан тоже. Живой прогон споткнулся ровно
    # здесь: модель поставила «run python main.py» на интерактивное
    # приложение, шаг провалился, и провал засчитался работе.
    parts = guard.split_command(command)
    if len(parts) == 2 and parts[0].lower().startswith("python") and _waits_for_input(parts[1]):
        return True, f"{parts[1]} ждёт ввода — запускать в прогоне нечем, пропускаем"
    verdict = guard.check(f"выполнить команду: {command}", f"в каталоге {guard.get_workspace()}")
    if verdict != guard.ALLOW:
        return False, guard.verdict_message(verdict, f"выполнить {command}")

    run = execute(command)
    return run.ok, f"код возврата {run.code}; {clip(run.text(), 400) or '(вывода нет)'}"


def _planned_modules(state: State) -> set[str]:
    """Имена модулей, которые план собирался создать.

    Берётся из плана, а не из каталога: файл мог не написаться, и вот
    тогда это и важно. Модуль, названный в плане, — свой по замыслу,
    и искать его в сети нельзя ни при каких обстоятельствах.
    """
    steps = state.extra.get("plan", {}).get("steps", [])
    names = set()
    for step in steps:
        target = str(step.get("target", "")).strip()
        if step.get("action") == CREATE and target.endswith(".py"):
            names.add(target.rsplit("/", 1)[-1][: -len(".py")])
    return names


def node_deps(state: State) -> State:
    """Разбирается с зависимостями написанного кода.

    Узел графа, а не шаг плана, и это принципиально. Какие пакеты нужны —
    вычисляется: разобрать импорты написанных файлов и спросить
    у интерпретатора проекта, какие из них не разрешаются. Спросить
    об этом модель значит получить правдоподобный ответ вместо верного:
    она ставит `requests` в задаче без единого сетевого вызова
    и не ставит `pyyaml` для `import yaml`, потому что имена не совпадают.

    Установка при этом всё равно проходит через подтверждение человеком:
    вычислить, ЧТО нужно, можно; решить, можно ли это ставить, — нет.

    Каркас узел пропускает целиком. Импорты в каркасе — предположение
    модели о коде, которого ещё нет, и ставить по ним пакеты значит
    менять окружение человека ради догадки. Живой прогон показал цену:
    на «напиши каркас переводчика» в файле оказалось `import translate`,
    и агент пошёл искать такой пакет.
    """
    if wants_scaffold(state.user_input):
        state.extra["missing_packages"] = []
        state.extra.setdefault("log", []).append(
            "зависимости: пропущены — просили каркас, кода в нём ещё нет"
        )
        return state

    # Модули, которые ПЛАН собирался создать, своими считаются независимо
    # от того, лежат ли они на диске. Иначе провалившийся шаг создания
    # превращает свой же модуль в чужой пакет из сети: живой прогон
    # на задаче про квадратное уравнение не смог написать `calculator.py`,
    # следующий шаг написал `import calculator` — и агент предложил
    # поставить `calculator` с PyPI. Человек согласился, и в окружение
    # приехал чужой пакет с подходящим именем.
    planned = _planned_modules(state)

    missing: list[str] = []
    for path in state.extra.get("touched", []):
        try:
            text = guard.resolve_path(path).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError, guard.OutsideWorkspace):
            continue
        for module in env.missing_imports(text):
            if module in planned:
                continue
            package = env.package_for(module)
            if package not in missing:
                missing.append(package)

    state.extra["missing_packages"] = missing
    if not missing:
        return state

    result = env.install(" ".join(missing))
    state.extra["deps_result"] = result
    state.extra.setdefault("log", []).append(f"зависимости: {result}")
    return state


def node_verify(state: State) -> State:
    """Проверяет работу и оставляет в состоянии только то, что нужно починке.

    Проверка бывает трёх видов, и выбирает между ними код, а не модель:

      * есть файлы тестов — прогоняем pytest;
      * тестов нет, программа НЕ ждёт ввода — запускаем её;
      * тестов нет, программа ждёт ввода — импортируем файл.

    Третий случай появился из живого прогона и стоил отката готовой
    работы. Агент написал калькулятор, который ждёт ввода с клавиатуры,
    проверка запустила его без stdin, тот честно упал с `EOFError` —
    и конвейер счёл рабочее приложение сломанным. Программу, которая
    ждёт ввода, запуском не проверить: у проверки нет пользователя.
    Импорт же отвечает на вопрос, на который ответить можно: файл
    разбирается, выполняется до `__main__` и не падает по дороге.

    Отдельно: если план ОБЕЩАЛ тесты (`wants_tests`), а тестов на диске
    нет, прогон считается провалившимся, и подменять проверку запуском
    нельзя. Живой прогон показал и это: модель написала модуль
    с заглушками `pass`, файл тестов потеряла по таймауту, `python
    cart.py` отработал с кодом 0 — и агент отчитался «Готово».
    """
    target = state.extra.get("tests", "")
    tests = _test_files(state)

    if not tests and not target and state.extra.get("wants_tests"):
        # Обещанных тестов нет. Чинить это НЕЛЬЗЯ: не хватает файла,
        # а починка умеет только править существующие. Живой прогон
        # показал, во что обходится попытка: цикл починки взял main.py,
        # увидел в тексте ошибки «план обещал тесты» — и дописал туда
        # тестовые функции. Дважды. После чего откатил вместе с ними
        # три нормально написанных файла.
        #
        # Поэтому `unverifiable`, а не просто «красная проверка»:
        # прогон идёт к итогу, недоделанное остаётся на диске,
        # а человек читает, чего не хватает.
        state.extra["verified_by"] = "нечем"
        state.extra["unverifiable"] = True
        state.extra["tests_green"] = False
        state.extra["failure"] = (
            "план обещал тесты, но ни одного файла test_*.py не появилось — "
            "проверить работу нечем, а починкой файл не создать"
        )
        return state

    if tests or target:
        where = f" {target}" if target else ""
        run = execute(f"python -m pytest{where} -q --no-header", timeout=max(guard.get_policy().timeout, 180.0))
        green = suite_passed(run)
        state.extra["verified_by"] = "pytest"
    else:
        entry = _entry_point(state)
        if not entry:
            # «Нечем проверить» — это НЕ провал. Агент мог сделать ровно
            # то, о чём просили: написать батник, файл настроек, README.
            # Проверить такое в этой главе нечем, и объявлять работу
            # сломанной за то, что у нас нет для неё проверки, — способ
            # выбросить правильно сделанное. Отдельный флаг, а не
            # `tests_green=False`, ровно поэтому.
            state.extra["verified_by"] = "нечем"
            state.extra["unverifiable"] = True
            state.extra["tests_green"] = False
            state.extra["failure"] = ""
            return state

        limit = max(guard.get_policy().timeout, 60.0)
        if wants_scaffold(state.user_input):
            # Каркас проверяется РАЗБОРОМ, и ничем сильнее.
            #
            # Запуск не подходит: тела пустые, `main()` с многоточием
            # внутри отработает с кодом 0 всегда, и отчёт «проверено
            # запуском» был бы неправдой. Импорт не подходит тоже,
            # и это стоило отката готовой работы: модель написала
            # в каркасе `import translate`, пакета с таким именем
            # в окружении нет — и правильно сделанный каркас объявился
            # бы сломанным за догадку о будущем коде. Разбор отвечает
            # на единственный вопрос, который к каркасу имеет смысл.
            run = execute([interpreter(), "-m", "py_compile", entry], timeout=limit)
            state.extra["verified_by"] = f"разбор {entry} (просили каркас, выполнять в нём нечего)"
        elif asks_input_on_import(entry):
            # Ввод стоит на верхнем уровне модуля: импорт его ВЫПОЛНИТ
            # и упадёт тем же EOFError, от которого импорт и должен был
            # спасти. Живой прогон на этом откатил правильно написанное
            # приложение. Остаётся разбор — он ничего не выполняет.
            run = execute([interpreter(), "-m", "py_compile", entry], timeout=limit)
            state.extra["verified_by"] = (
                f"разбор {entry} (ввод спрашивается сразу при импорте, выполнять нечем)"
            )
        elif _waits_for_input(entry):
            module = entry.rsplit("/", 1)[-1][: -len(".py")]
            run = execute([interpreter(), "-c", f"import {module}"], timeout=limit)
            state.extra["verified_by"] = f"импорт {entry} (программа ждёт ввода, запускать её нечем)"
        else:
            # Запуск здесь идёт БЕЗ guard.check, и это правило, а не
            # недосмотр. Спрашивать нечего: человек подтвердил план,
            # в котором стоит шаг проверки, и подтвердил каждую запись
            # в файл, который сейчас запускается. Второй вопрос про то
            # же самое — не защита, а приучение жать «y» не читая.
            # То же исключение и по той же причине сделано у `run_tests`
            # и `run_lint`, и там оно записано в shell.py.
            run = execute([interpreter(), entry], timeout=limit)
            state.extra["verified_by"] = f"запуск {entry}"
        green = run.ok

    state.extra["tests_green"] = green
    state.extra["failure"] = "" if green else first_error(run.text())
    state.extra["verify_output"] = clip(run.text(), 800)
    state.extra["verify_seconds"] = round(run.seconds, 1)
    return state


def _asks_input(node: ast.AST) -> bool:
    """Есть ли внутри узла вызов `input(...)` или обращение к `sys.stdin`.

    Ищется именно ВЫЗОВ, а не слово: «input» встречается и в имени
    переменной (`user_input`), и в комментарии, и в тексте подсказки.
    """
    for inner in ast.walk(node):
        if isinstance(inner, ast.Call) and isinstance(inner.func, ast.Name) and inner.func.id == "input":
            return True
        if isinstance(inner, ast.Attribute) and inner.attr == "stdin":
            return True
    return False


def _main_guard(node: ast.AST) -> bool:
    """Это блок `if __name__ == "__main__":`?"""
    if not isinstance(node, ast.If) or not isinstance(node.test, ast.Compare):
        return False
    left = node.test.left
    return isinstance(left, ast.Name) and left.id == "__name__"


def _module_tree(path: str) -> ast.Module | None:
    """Разбор файла или None, если он не читается и не разбирается."""
    try:
        return ast.parse(guard.resolve_path(path).read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, SyntaxError, ValueError, guard.OutsideWorkspace):
        return None


def _waits_for_input(path: str) -> bool:
    """Читает ли программа ввод с клавиатуры — где угодно в файле."""
    tree = _module_tree(path)
    return tree is not None and _asks_input(tree)


def asks_input_on_import(path: str) -> bool:
    """Спросит ли файл ввод ПРИ ИМПОРТЕ, а не только при запуске.

    Разница стоила отката правильно написанного приложения, и вот она.
    Проверка «программа ждёт ввода — значит импортируем» опирается
    на молчаливое допущение, что интерактив лежит под `if __name__ ==
    "__main__":`. Модель на 3B это допущение не разделяет: живой прогон
    дал файл, где `input()` стоит прямо на верхнем уровне модуля.
    Импорт такой модуль ВЫПОЛНЯЕТ — и падает тем же `EOFError`,
    от которого импорт и должен был спасти.

    Поэтому смотрим не «есть ли input», а «выполнится ли он при
    импорте»: тела функций и классов при импорте не исполняются,
    блок `__main__` при импорте не исполняется тоже, всё остальное —
    исполняется.
    """
    tree = _module_tree(path)
    if tree is None:
        return False
    for statement in tree.body:
        if isinstance(statement, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        if _main_guard(statement):
            continue
        if _asks_input(statement):
            return True
    return False


def _test_files(state: State) -> list[str]:
    """Файлы тестов среди написанных агентом и лежащих в каталоге."""
    root = guard.get_workspace()
    found = [guard.relative(p) for p in sorted(root.glob("test_*.py"))]
    for path in state.extra.get("touched", []):
        name = path.rsplit("/", 1)[-1]
        if name.startswith("test_") and path not in found:
            found.append(path)
    return found


def _entry_point(state: State) -> str:
    """Что запускать, когда тестов нет: последний написанный не-тестовый файл."""
    for path in reversed(state.extra.get("touched", [])):
        if path.endswith(".py") and not path.rsplit("/", 1)[-1].startswith("test_"):
            return path
    return ""


def node_read(state: State) -> State:
    """Перечитывает файл, который будет чиниться.

    Отдельным узлом, а не строчкой внутри правки: именно сюда ведёт
    стрелка назад от провалившихся тестов, и в трейсе прогона должно
    быть видно, что файл перечитан.
    """
    path = _file_to_fix(state)
    if not path:
        state.error = "Нечего чинить: агент не тронул ни одного файла."
        return state
    state.extra["path"] = path
    state.retrieved = _read_pair(state, path)
    return state


def _read_pair(state: State, path: str) -> str:
    """Читает чинимый файл ВМЕСТЕ с его парой: модуль и тест к нему.

    Пару приходится показывать обе, и это выяснилось наблюдением,
    а не рассуждением. Упавший тест — это утверждение о ДВУХ файлах:
    «вот что я жду» и «вот что написано». Показав модели только один
    из них, мы просим её починить договор, половину которого она не
    видит. В прогоне так и вышло: в контексте лежал `test_todo.py`,
    а модель переписала `todo.py` — по памяти, вслепую, и угадала.
    Второй раз могла и не угадать.

    Пара ищется по имени: `test_x.py` <-> `x.py`. И только среди файлов,
    которые агент писал сам: подтягивать в контекст чужой модуль,
    который агент не имеет права менять, значит звать его туда,
    куда ему нельзя.
    """
    text = f"Файл {path}:\n{read_lines(path, '1', str(CONTEXT_LINES))}"

    name = path.rsplit("/", 1)[-1]
    prefix = path[: len(path) - len(name)]
    counterpart = prefix + (name[len("test_"):] if name.startswith("test_") else f"test_{name}")

    if counterpart in state.extra.get("touched", []):
        text += f"\n\nПарный файл {counterpart}:\n{read_lines(counterpart, '1', str(CONTEXT_LINES))}"
    return text


def _file_to_fix(state: State) -> str:
    """Какой файл чинить после провала проверки.

    Два правила по порядку.

    **Первое: файл, названный в тексте ошибки** — если этот файл писал
    сам агент. Отчёт pytest указывает на строку и файл, и спорить
    с ним нечем: сломано там. Оговорка про «писал сам» здесь и есть
    вся защита от жульничества: агент правит СВОИ файлы, включая
    написанные им тесты, и не трогает те, что были в проекте до него.
    Чужой тест, который он не может пройти, — это провал задачи,
    а не приглашение переписать тест.

    **Второе, если ошибка ничего не назвала: последний написанный
    не тестовый файл.** Упавший тест обычно означает ошибку
    в проверяемом коде, и начинать разумнее с него.

    Первая версия правила запрещала трогать тесты вообще, и на живой
    модели это вышло боком: 7B написала сломанный тест (`UnboundLocalError`
    в самом тесте), а починка упорно правила исправный модуль. Оба круга
    ушли впустую.
    """
    touched = state.extra.get("touched", [])
    failure = state.extra.get("failure", "") + " " + state.extra.get("verify_output", "")

    for path in touched:
        name = path.rsplit("/", 1)[-1]
        if re.search(rf"\b{re.escape(name)}\b", failure):
            return path

    for path in reversed(touched):
        if not path.rsplit("/", 1)[-1].startswith("test_"):
            return path
    return touched[-1] if touched else state.extra.get("path", "")


def node_edit(state: State) -> State:
    """Второй узел, где решает модель: починка после провала проверки."""
    state.extra["attempt"] = int(state.extra.get("attempt", 0)) + 1
    path = state.extra.get("path", "")

    before = guard.change_count()
    result = _ask_for_edit(state, path, "", failure=state.extra.get("failure", ""))
    state.extra["edit_result"] = result
    # Успех правки определяется по журналу изменений, а не по тексту
    # ответа инструмента. Первая версия смотрела на текст — искала в нём
    # слова «не применена» — и попалась на живой модели: та назвала файл,
    # которого в проекте нет, инструмент честно ответил «Нет такого
    # файла», а проверка по словам этого не заметила и засчитала правку.
    # Дальше конвейер гонял тесты по нетронутому файлу и удивлялся,
    # почему они красные. Текст ошибки пишут пять разных мест,
    # а журнал один — и правка либо легла на диск, либо нет.
    state.extra["edit_ok"] = guard.change_count() > before
    if state.extra["edit_ok"]:
        _remember(state, path)
    return state


def _ask_for_edit(state: State, path: str, detail: str, failure: str = "") -> str:
    """Один запрос к модели за правкой и её применение."""
    user = f"Задача: {state.user_input}\n"
    if detail:
        user += f"Шаг плана: {detail}\n"
    # `retrieved` уже приходит с заголовками файлов, когда его собрал
    # `_read_pair`. Заворачивать его во второй заголовок значит написать
    # «Файл a.py: Файл a.py: ...» и запутать модель ровно там, где ей
    # надо точно понять, куда писать.
    user += f"\n{state.retrieved}\n" if state.retrieved.startswith("Файл ") else f"\nФайл {path}:\n{state.retrieved}\n"
    if failure:
        user += f"\nПрошлая попытка не прошла проверку. Ошибка:\n{failure}\n"

    messages = [{"role": "system", "content": EDIT_RULES}, {"role": "user", "content": user}]
    try:
        with using_model(coder_model()):
            raw = request_model(messages, response_format=edit_schema())
        data = json.loads(raw)
    except Exception as exc:  # noqa: BLE001
        return f"модель не дала правку: {exc}"

    state.extra["edit_form"] = str(data.get("form", ""))
    return apply_edit(data, default_path=path)


def normalize_edit(data: dict) -> tuple[dict, str]:
    """Приводит ответ модели к той форме, которую она имела в виду.

    Правило пока одно, и оно из живого прогона. На задаче «добавь
    в calc.py интерактивность» модель раз за разом отвечала формой
    `anchor` с ПУСТЫМ якорем и непустой заменой:

        {"form": "anchor", "path": "calc.py", "old": "", "new": "...код..."}

    Пустой якорь не адресует ничего, и как замена этот ответ бессмыслен.
    Но смысл в нём есть, и ровно один: «допиши вот это». Форма `append`
    для этого и заведена — а модель её не выбрала, хотя правило про неё
    стоит в промпте ПЕРВЫМ пунктом.

    Отсюда вывод шире одного случая: **новая форма в промпте не делает
    модель её использующей.** Слабая модель отвечает тем, что чаще
    встречалось в обучении, и подстраиваться приходится коду. Дописать
    сюда правило дешевле, чем спорить промптом, — и, в отличие от спора,
    это проверяется тестом.

    Подмена не молчаливая: она возвращается второй половиной пары
    и попадает в отчёт, чтобы в трейсе было видно, что ответ модели
    поняли не буквально.
    """
    form = str(data.get("form", "")).strip()
    if form != ANCHOR:
        return data, ""
    if str(data.get("old", "")).strip() or not str(data.get("new", "")).strip():
        return data, ""

    fixed = dict(data)
    fixed["form"] = APPEND
    fixed["content"] = data.get("new", "")
    return fixed, "(пустой якорь — поняли как дописывание в конец) "


def apply_edit(data: dict, default_path: str = "") -> str:
    """Применяет правку, описанную ответом модели.

    Работа идёт через инструменты из fs.py, а не через `edits.py`
    напрямую. Разница существенная: в инструментах живут проверка
    границ, подтверждение и запись в журнал отката. Обойти их «ради
    удобства конвейера» значит завести второй путь на диск, у которого
    другие правила, — и рано или поздно правка уедет мимо всех проверок.
    """
    data, hint = normalize_edit(data)
    form = str(data.get("form", "")).strip()
    path = str(data.get("path", "")).strip() or default_path
    if not path:
        return "Правка не применена. Модель не назвала файл."

    path, note = _fix_path(path, default_path)
    note = hint + note

    gaps = missing_fields(data)
    if gaps:
        return f"Правка не применена. В ответе нет полей: {', '.join(gaps)}."

    if form == ANCHOR:
        return note + edit_file(path, str(data.get("old", "")), str(data.get("new", "")))
    if form == LINES:
        return note + replace_lines(
            path, str(data.get("start", "")), str(data.get("end", "")), str(data.get("content", ""))
        )
    if form == FULL:
        return note + write_file(path, str(data.get("content", "")))
    if form == APPEND:
        return note + append_to_file(path, str(data.get("content", "")))
    return f"Правка не применена. Неизвестная форма: {form!r}."


def _fix_path(path: str, default_path: str) -> tuple[str, str]:
    """Возвращает путь, по которому действительно есть файл, и пояснение.

    Нужно из-за поведения, которое видно только на настоящей модели:
    она называет в ответе файл, которого в проекте нет, — при том, что
    правильный путь напечатан у неё прямо в контексте. Случаи бывают
    разные: похожее имя из соседнего каталога, привычное `main.py`,
    транслитерация нелатинского имени.

    Чинить это промптом бесполезно: правило «бери путь как дан» в
    EDIT_RULES уже есть, и модель нарушает его всё равно. Поэтому
    чинится кодом: файл, который правится, выбрал конвейер, и если
    названного моделью пути нет, а путь от конвейера есть — правим тот,
    что есть. Подмена не молчаливая: она попадает в отчёт, и по нему
    видно, что модель промахнулась.
    """
    if not default_path or path == default_path:
        return path, ""
    try:
        if guard.resolve_path(path).is_file():
            return path, ""
        if guard.resolve_path(default_path).is_file():
            return default_path, f"(модель назвала файл {path}, правим {default_path}) "
    except guard.OutsideWorkspace:
        return path, ""
    return path, ""


def node_rollback(state: State) -> State:
    """Возвращает файлы в состояние до прогона.

    Вызывается только когда попытки исчерпаны. Наполовину написанный
    проект — худший из исходов: он выглядит как сделанная работа
    и ломается позже, у того, кто не знает, что здесь был агент.
    """
    state.extra["rolled_back"] = guard.rollback()
    return state


def node_done(state: State) -> State:
    """Собирает итог прогона в человекочитаемый ответ.

    Исходов четыре, и различать их обязательно — отчёт, которому нельзя
    верить, хуже отсутствия отчёта:

      * **готово** — проверка зелёная И ни один шаг не провалился;
      * **сделано, но проверить нечем** — шаги прошли, а проверять
        написанное этой главе нечем (батник, файл настроек, README);
      * **сделано не всё** — что-то провалилось, хотя проверка зелёная;
      * **не получилось** — проверка красная, попытки исчерпаны, откат.

    Второй исход появился из живого прогона: агент написал батник —
    правильно написал, — а конвейер объявил это провалом и откатил,
    потому что `.bat` ему нечем проверить.
    """
    attempts = int(state.extra.get("attempt", 0))
    log = state.extra.get("log", [])
    failed = state.extra.get("failed_steps", [])
    body = "\n".join(f"  {line}" for line in log)
    tail = "\nПровалились:\n" + "\n".join(f"  {name}" for name in failed) if failed else ""

    if state.extra.get("tests_green") and not failed:
        how = state.extra.get("verified_by", "проверка")
        repairs = f" (починок: {attempts})" if attempts else ""
        state.answer = f"Готово. Проверено: {how}{repairs}.\n{body}"
    elif state.extra.get("unverifiable"):
        head = (
            "Сделано, но ПРОВЕРИТЬ НЕЧЕМ: ни тестов, ни запускаемого файла "
            "среди написанного. Посмотрите результат сами."
        )
        if failed:
            head = f"Сделано НЕ ВСЁ, и проверить нечем: провалилось шагов — {len(failed)}."
        state.answer = f"{head}\n{body}{tail}"
    elif state.extra.get("tests_green") and failed:
        state.answer = (
            f"Сделано НЕ ВСЁ: провалилось шагов — {len(failed)}, "
            f"хотя проверка ({state.extra.get('verified_by', '?')}) зелёная.\n"
            f"{body}{tail}"
        )
    elif state.extra.get("rolled_back") is not None:
        restored = state.extra.get("rolled_back") or []
        head = (
            f"Не получилось за {attempts} попыт(ки). Всё сделанное откачено."
            if restored
            else f"Не получилось за {attempts} попыт(ки). До записи на диск дело не дошло."
        )
        state.answer = (
            head
            + (f"\n{body}" if body else "")
            + ("\n" + "\n".join(f"  {r}" for r in restored) if restored else "")
            + (f"\nПоследняя ошибка: {state.extra.get('failure', '')}" if state.extra.get("failure") else "")
        )
    elif state.error:
        state.answer = f"{state.error}\n{body}" if body else state.error
    elif not state.answer:
        state.answer = f"Прогон закончен.\n{body}" if body else "Прогон закончен, делать было нечего."
    return state


