def build_pipeline(max_steps: int = MAX_GRAPH_STEPS) -> Graph:
    """Собирает конвейер: девять узлов, четыре условных ребра."""
    graph = Graph(max_steps=max_steps)
    graph.node(PLAN, node_plan)
    graph.node(CONFIRM, node_confirm)
    graph.node(STEP, node_step)
    graph.node(DEPS, node_deps)
    graph.node(VERIFY, node_verify)
    graph.node(READ_NODE, node_read)
    graph.node(EDIT_NODE, node_edit)
    graph.node(ROLLBACK, node_rollback)
    graph.node(DONE, node_done)

    graph.edge(PLAN, CONFIRM)
    graph.conditional(CONFIRM, edge_after_confirm, targets=(STEP, END))
    graph.conditional(STEP, edge_after_step, targets=(STEP, DEPS))
    graph.edge(DEPS, VERIFY)
    graph.conditional(VERIFY, edge_after_verify, targets=(DONE, READ_NODE, ROLLBACK))
    graph.conditional(READ_NODE, edge_after_read, targets=(EDIT_NODE, DONE))
    graph.conditional(EDIT_NODE, edge_after_edit, targets=(VERIFY, READ_NODE, ROLLBACK))
    graph.edge(ROLLBACK, DONE)
    graph.edge(DONE, END)

    graph.entry(PLAN)
    return graph


def run_pipeline(task: str, tests: str = "", plan: Plan | None = None, **kwargs) -> State:
    """Прогоняет конвейер по задаче. Возвращает состояние целиком.

    Состояние целиком, а не только ответ: по нему видно и маршрут
    (`state.trace()`), и число починок, и какие файлы написаны, и чем
    проверяли. Для замеров главы это и есть исходные данные.
    """
    state = State(user_input=task)
    if tests:
        state.extra["tests"] = tests
    if plan is not None:
        state.extra["plan"] = plan.to_dict()
    guard.forget_changes()
    return build_pipeline().run(state, **kwargs)
