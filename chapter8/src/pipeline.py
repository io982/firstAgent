def edge_after_confirm(state: State) -> str:
    """Человек не разрешил — прогон кончается, ничего не сделав."""
    return STEP if state.extra.get("approved") else END


def edge_after_step(state: State) -> str:
    """Первая стрелка назад: пока в плане есть шаги, идём в тот же узел."""
    plan = Plan.from_dict(state.extra.get("plan", {}))
    if int(state.extra.get("cursor", 0)) < len(plan.steps):
        return STEP
    return DEPS


def edge_after_verify(state: State) -> str:
    """Вторая стрелка назад — та, ради которой конвейер и записан графом.

    Отдельная ветка для «проверить нечем», и она из живого прогона.
    Человек попросил батник для запуска calc.py; агент его написал —
    правильно написал, — но проверять `.bat` в этой главе нечем: тестов
    нет, запускаемого питоновского файла среди написанного нет. Прогон
    считался провалившимся, цикл починки два круга бился о пустоту,
    и правильно сделанная работа откатывалась.

    Чинить нечего, если не сломано. «Не смогли проверить» и «проверили,
    и оно сломано» — разные исходы, и второй из первого не следует.
    """
    if state.extra.get("tests_green"):
        # Проверки прошли, но разбор говорит, что сделано не то. Один
        # круг починки такое сомнение стоит: претензии конкретны, они
        # сверены с файлом, и починка получит их вместо «исправь».
        # Второго круга не будет и отката тоже: работу, прошедшую все
        # механические проверки, из-за мнения модели не удаляют.
        if state.extra.get("doubt") and not state.extra.get("doubted"):
            state.extra["doubted"] = True
            state.extra["failure"] = state.extra["doubt"]
            return READ_NODE
        return DONE
    if state.extra.get("unverifiable"):
        return DONE
    if int(state.extra.get("attempt", 0)) < MAX_ATTEMPTS:
        # К чтению, а не сразу к правке: файл на диске изменился
        # прошлой попыткой, и модель должна увидеть его таким, какой он есть.
        return READ_NODE
    return ROLLBACK


def edge_after_read(state: State) -> str:
    """Чинить нечего — идём к итогу, а не в правку пустоты."""
    return DONE if state.error else EDIT_NODE


def edge_after_edit(state: State) -> str:
    """Правка легла — проверяем. Не легла — ещё круг или откат.

    Ещё круг именно здесь, а не после проверки: правка, которая не легла
    на файл, до проверки не доходит вовсе, и гонять тесты незачем.
    """
    if state.extra.get("edit_ok"):
        return VERIFY
    if int(state.extra.get("attempt", 0)) < MAX_ATTEMPTS:
        state.extra["failure"] = str(state.extra.get("edit_result", ""))
        return READ_NODE
    return ROLLBACK


