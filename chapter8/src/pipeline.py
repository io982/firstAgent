# Как агент пишет файл: "direct" — одним запросом целиком,
# "skeleton" — сначала состав файла, потом дописывание тел.
#
# Второй режим появился из правдоподобной гипотезы, и замер её
# ОПРОВЕРГ. Гипотеза была такая: базовые Coder-модели (не Instruct)
# обучены на ДОПОЛНЕНИЕ кода, а просьба «напиши файл целиком
# по описанию» — задача на исполнение инструкции, то есть ровно то,
# чему их не учили. Значит, надо перевести задачу в форму дополнения:
#
#   1. коротким структурированным ответом получить СОСТАВ файла —
#      имена функций, аргументы, назначение одной фразой;
#   2. скелет по этому составу собрать КОДОМ: определения с описанием
