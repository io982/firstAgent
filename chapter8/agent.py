def work(task: str, tests: str = "", langgraph: bool = False) -> str:
    """Делает задачу: план, подтверждение, работа по плану, проверка.

    Главный вход агента. Сюда попадает всё, что похоже на задачу, —
    и «напиши приложение с нуля», и «поправь функцию add». Разницу
    между этими двумя случаями разбирает планировщик, а не человек:
    план из кода для правки названного файла, план от модели для всего
    остального.
    """
    if langgraph:
        from chapter8.src.pipeline_lg import LANGGRAPH_AVAILABLE, run_langgraph_pipeline

        if not LANGGRAPH_AVAILABLE:
            return "LangGraph не установлен. Поставьте: pip install langgraph"
        state = run_langgraph_pipeline(task, tests=tests)
    else:
        state = run_pipeline(task, tests=tests)

    parts = [f"🧩 Маршрут прогона: {state.trace()}"]
    if state.extra.get("plan_text"):
        parts.append(state.extra["plan_text"])
    if state.extra.get("edit_form"):
        parts.append(f"Форма правки: {state.extra['edit_form']}, попыток: {state.extra.get('attempt')}")
    parts.append(state.answer or "Прогон закончился без ответа.")
    return "\n".join(parts)


def show_plan(task: str, use_model: bool | None = None) -> str:
    """Составляет план и показывает его, ничего не делая.

    Нужно чаще, чем кажется: план — самый дешёвый способ понять,
    правильно ли агент понял задачу, и стоит он в худшем случае один
    запрос к модели вместо целого прогона с правками и тестами.

    `use_model` перекрывает умолчание — командой «план моделью». По
    умолчанию план составляет код: замер главы показал, что на 3B так
    получается и точнее, и в разы быстрее.
    """
    plan = make_plan(task, use_model=use_model)
    return render_plan(plan, validate_plan(plan))


def workspace_report() -> str:
    """Где агент работает и что ему сейчас разрешено."""
    policy = guard.get_policy()
    lines = [
        f"Рабочий каталог: {policy.root}",
        f"Режим подтверждения: {policy.mode}"
        + (" + сухой прогон (ничего не пишется)" if policy.dry_run else ""),
        "Разрешённые программы: "
        + (", ".join(policy.allowed) if policy.allowed else "ЛЮБЫЕ (белый список выключен)"),
        f"Предел по времени: {policy.timeout:.0f} с",
        f"Планировщик: {planner_module.PLANNER}"
        + (f" (модель {planner_model()})" if planner_module.PLANNER == "model" else " — код, модель только с нуля"),
        f"Модель для кода: {coder_model()}",
    ]
    lines.append(env_report())
    if is_repo():
        lines.append(f"Ветка git: {current_branch() or 'неизвестна'}")
    changed = guard.changed_files()
    lines.append(
        "Изменено агентом: " + (", ".join(guard.relative(p) for p in changed) if changed else "ничего")
    )
    return "\n".join(lines)


