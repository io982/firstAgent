def ask_agent(user_input: str, conversations: dict | None = None, max_iterations: int = 5) -> str:
    """Ответ на ВОПРОС о коде. Задачи идут не сюда, а в конвейер.

    Своя обёртка, а не `chapter7.ask_agent`, ровно из-за одной строки:
    команду надо положить в состояние прогона. Без неё узлы Главы 7
    взяли бы весь реестр специалистов, и вернулись бы и погода,
    и факты о пользователе.
    """
    if not is_safe_query(user_input):
        return "⚠️ Обнаружена попытка инъекции промпта. Запрос отклонён."

    state = State(user_input=user_input)
    state.extra["team"] = TEAM
    state.extra["conversations"] = conversations if conversations is not None else {}
    state.extra["max_iterations"] = max_iterations

    state = GRAPH8.run(state)
    if state.error:
        print(f"⚠️ {state.error}")
    print(f"🧩 Маршрут прогона: {state.trace()}")
    return state.answer or "⚠️ Граф закончился без ответа."


