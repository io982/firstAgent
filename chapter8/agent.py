# Слова, по которым реплика считается ЗАДАЧЕЙ, а не вопросом.
#
# Список глагольный, и это главное в нём. «Где реализован калькулятор»
# и «поправь калькулятор» говорят про одно и то же, а делать по ним надо
# противоположное: на первое ответить текстом, по второму пойти и
# изменить файлы. Отличаются они ровно глаголом, поэтому предметных
# слов («функция», «файл», «тест») здесь нет — они есть в обеих репликах.
# Маркеры — ОСНОВЫ слов, а не слова целиком: `matches()` Главы 5 так
# и устроена, и это не придирка. Живой прогон споткнулся ровно об это:
# в списке стояло «добавь», человек написал «нужно добавить», совпадения
# не нашлось, и задача уехала отвечать текстом вместо того, чтобы
# править файл. Основа «добав» покрывает и «добавь», и «добавить»,
# и «добавим».
TASK_MARKERS = (
    # написать с нуля
    "напиш", "созда", "сдела", "реализ", "сгенерир", "наброса",
    # поправить существующее
    "поправ", "почин", "исправ", "испарв", "измен", "перепиш",
    "переимен", "отрефактор", "добав", "удал", "дополн", "допиш",
    # запустить и проверить
    "запуст", "прогон", "проверь линтером", "покрой тестами",
)

# Реплики, которые начинаются с глагола из списка, но задачей не являются.
# «Покажи git log» — это вопрос о состоянии, отвечать на него планом
# из трёх шагов было бы издевательством.
NOT_A_TASK = (
    "покажи", "расскаж", "объясн", "что такое", "как устроен", "где ",
    "что изменилось", "чем отлича",
)

CODER_NAME = "код"


def retrieve_workspace(user_input: str, budget: int) -> Retrieval:  # noqa: ARG001
    """Кладёт в контекст состояние рабочего каталога, а не фрагменты кода.

    У специалистов Главы 7 контекст — выдержки из текста, найденные
    заранее. Здесь иначе, и причина в том, что нужно кодинг-агенту:
    не «где про это написано», а «где мы сейчас, что уже изменено,
    в какой ветке и каким Python работаем». Фрагменты кода он достанет
    сам, инструментами, и достанет ровно те, что нужны, — в отличие
    от поиска, который кладёт похожее заранее и вслепую.

    Возвращается found=True всегда: пустой каталог — это не промах
    поиска, и передавать реплику некому.
    """
    # Заголовок нужен: без него модель принимает эту справку за готовый
    # ответ и просто пересказывает её человеку. На вопрос «а где батник?»
    # агент отвечал «ваш рабочий каталог — ...», что верно и бесполезно.
    lines = [
        "СПРАВКА О СОСТОЯНИИ (это не ответ на вопрос, а обстановка вокруг):",
        f"Рабочий каталог: {guard.get_workspace()}",
    ]
    policy = guard.get_policy()
    lines.append(f"Режим: {policy.mode}" + (", сухой прогон" if policy.dry_run else ""))
    lines.append(env_report())

    if is_repo():
        lines.append(f"Ветка git: {current_branch() or 'неизвестна'}")
    changed = guard.changed_files()
    if changed:
        lines.append("Агент уже менял в этой сессии: " + ", ".join(guard.relative(p) for p in changed))

    return "\n".join(lines)[: budget * 4], True


# Описание собирается объектом, а НЕ декоратором `@specialist`.
# Разница важная: декоратор кладёт специалиста в общий реестр Главы 7,
# и тогда команда Главы 8 подмешалась бы к её пятерым. Здесь команда
# своя и живёт только в этой главе — глобальный реестр специалистов
# она не трогает.
CODER = AgentSpec(
    name=CODER_NAME,
    role="работа с кодом: найти, изменить, запустить, проверить, зафиксировать",
    tools=CODER_TOOLS,
    rules=CODER_RULES,
    retrieve=retrieve_workspace,
)

TEAM = Team(members={CODER_NAME: CODER}, default=CODER_NAME)


def looks_like_task(text: str) -> bool:
    """Реплика — это задача на работу с кодом, а не вопрос о нём.

    Различаются они глаголом. «Где реализован калькулятор» — вопрос,
    на него отвечает поиск по коду. «Поправь калькулятор» — задача,
    и она уходит в конвейер: план, подтверждение, работа.

    Это и есть весь вход агента. Отдельной команды «сделай задачу»
    нет намеренно: человек, который сел работать с кодинг-агентом,
    пишет, что надо сделать, а не подбирает имя команды.
    """
    lowered = f" {text.lower().strip()} "
    if matches(lowered, NOT_A_TASK):
        return False
    return matches(lowered, TASK_MARKERS)


