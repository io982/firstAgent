"""
Агент Главы 8: кодинг-агент — пишет проекты, правит код, проверяет себя.

Человек говорит, что нужно сделать. Агент составляет план, показывает
его и ждёт «да». Дальше сам: создаёт файлы, пишет код и тесты,
разбирается с зависимостями, прогоняет проверку и чинит, если она
провалилась. Не вышло за две попытки — откатывает всё сделанное.

Что меняется по сравнению с Главой 7:

  * **инструменты действуют по-настоящему.** Девятнадцать новых: шесть
    файловых, четыре запуска, пять git, четыре про окружение. До этой
    главы худшее, что мог сделать агент, — ответить неправильно; теперь
    он пишет файлы, ставит пакеты и запускает команды. Поэтому первым
    в главе написан не инструмент, а `src/guard.py`;
  * **вход у агента один — задача.** Отдельной команды нет: реплика,
    начинающаяся с глагола действия («напиши», «поправь», «добавь»),
    уходит в конвейер; вопрос («где реализован калькулятор?») —
    исполнителю, и тот отвечает поиском по коду. Различает их глагол,
    а не предмет;
  * **команда сжалась до одного.** Глава 7 разделила универсального
    агента на пятерых; здесь обратное движение, и это не откат.
    Пятеро отвечали на вопросы, а вопросы бывают разные. Кодинг-агент
    делает работу, и работа у него одна. Из инструментов остались
    девятнадцать своих и шесть на поиск по коду от Главы 5: ни памяти,
    ни поиска по документам, ни калькулятора, ни погоды. `enum` схемы
    ответа — это список того, что агент может назвать, и каждое лишнее
    имя в нём — ошибка, которую он способен совершить;
  * **работа идёт конвейером, а не свободным циклом** (см. src/pipeline.py):
    план — подтверждение — шаги плана — зависимости — проверка, и две
    стрелки назад. Первая гоняет по шагам плана, вторая возвращает
    от провалившейся проверки к ПЕРЕЧИТЫВАНИЮ файла: после неудачной
    попытки файл на диске другой, и модель должна увидеть его новым;
  * **зависимости вычисляются, а не назначаются.** Какие пакеты нужны,
    видно из импортов написанного кода; спрашивать об этом модель значит
    получить правдоподобный ответ вместо верного. Установка при этом
    всё равно проходит через подтверждение человеком;
  * **у правки три формы** (см. src/edits.py). Замер главы развернул
    ожидание: форма с номерами строк выглядела лучшей — адрес
    `файл:строки` у нас уже есть от поиска Главы 5, — а на файле
    из десяти функций перестала работать совсем. Держится замена
    по якорю, и она стоит в промпте правки по умолчанию;
  * **план для правки строит код, для работы с нуля — модель**
    (см. src/planner.py). Развилка проверяемая: задача называет
    существующий файл или нет. На задачах правки замер дал коду 5 из 5
    против 2 из 5 у модели; на задачах с нуля у кода ответа нет вовсе —
    придумать имена файлов эвристикой нельзя;
  * **модель для кода — отдельный параметр** (`AGENT_CODER_MODEL`),
    как планировщик. Какую ставить, говорит замер главы, а не карточка
    модели на Hugging Face;
  * **тот же конвейер собран на LangGraph** (см. src/pipeline_lg.py) —
    те же девять узлов, тот же State, другой сборщик. Зависимость
    необязательная, и цена её названа числом.

Что НЕ меняется: поиск по коду Глав 5-6, работа с контекстом Главы 3,
граф Главы 7 — всё используется как есть. Изменилось не устройство,
а состав команды.

Цена, которую честно назвать сразу. Агент не заперт в песочнице:
рабочий каталог он не покидает, но внутри него может переписать любой
файл, поставить любой пакет и запустить любую команду — белого списка
программ по умолчанию нет. Единственная проверка, кроме каталога, —
человек, читающий команду перед тем, как нажать `y`. Запускайте главу
на копии проекта, а не на единственной.
"""
