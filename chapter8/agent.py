def node_route_single(state: State) -> State:
    """Кто отвечает. Отвечать некому, кроме одного, — и это весь узел.

    Маршрутизатор Главы 7 остался в Главе 7 вместе с пятерыми, между
    которыми было что выбирать. Здесь узел сохранён формой, а не
    содержанием: граф Главы 7 ждёт узел с именем `route`, и подменить
    его функцию честнее, чем собирать граф заново копией четырёх строк.
    """
    state.agent = CODER_NAME
    if CODER_NAME not in state.tried:
        state.tried.append(CODER_NAME)
    return state


def build_graph8(max_steps: int = 12) -> Graph:
    """Граф Главы 7, у которого заменён один узел — маршрутизация."""
    graph = chapter7_agent.build_graph(max_steps=max_steps)
    graph.nodes["route"] = node_route_single
    return graph


