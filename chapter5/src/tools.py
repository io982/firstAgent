@tool
def search_code(query: str) -> str:
    """Ищет код проекта по смыслу вопроса: где что реализовано и как работает.

    Вызывай, когда вопрос про устройство кода, а точное имя неизвестно:
    «где считается бюджет контекста», «как устроена индексация».
    Если известно точное имя функции или класса — быстрее find_symbol.

    Args:
        query: Вопрос своими словами, а не одно ключевое слово
    """
    if not query or not query.strip():
        return "Ошибка: пустой запрос. Передай в query вопрос целиком."

    # Запрос переписывается в «кодовый» и здесь, а не только в автопоиске
    # агента. Замер: модель, вызвавшая search_code с русским запросом
    # «где реализован калькулятор», не нашла ничего и ответила «калькулятор
    # в проекте не реализован». С переписыванием тот же вызов находит
    # chapter1/agent.py:82.
    try:
        context = get_code_index().retrieve(expand_query(query), budget_tokens=get_code_budget())
    except EmbeddingError as e:
        return (
            f"Ошибка поиска по коду: {e}. Скажи пользователю, что индекс кода "
            f"недоступен, и не отвечай по памяти."
        )

    if not context:
        return (
            f"❌ В коде проекта ничего не найдено по запросу «{query}». "
            f"Так и скажи пользователю. НЕ ВЫДУМЫВАЙ ни файлы, ни номера строк."
        )

    return (
        "🔍 Самые похожие фрагменты кода. Это КАНДИДАТЫ, а не готовый ответ: "
        "поиск возвращает их всегда, даже когда нужного кода в проекте нет. "
        "Отвечай только по ним и обязательно назови адрес из шапки фрагмента "
        f"(файл:строки). Номера строк бери ТОЛЬКО из шапок.\n\n{context}"
    )


