# Сколько токенов найденного кода инструмент имеет право вернуть.
# Значение по умолчанию — заглушка: настоящее считает агент, потому что
# известно оно только после сборки системного промпта (см. agent.py).
DEFAULT_CODE_BUDGET = 600

_code_budget = DEFAULT_CODE_BUDGET

# Сколько определений показываем, если имя нашлось в нескольких местах.
# Больше пяти — это уже не ответ, а список.
MAX_DEFINITIONS = 5


def set_code_budget(tokens: int) -> None:
    """Ставит потолок на объём выдачи поиска по коду (зовётся из agent.py)."""
    global _code_budget
    _code_budget = max(100, int(tokens))


def get_code_budget() -> int:
    return _code_budget


