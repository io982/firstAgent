@tool
def find_symbol(name: str) -> str:
    """Находит, где определена функция, класс, метод или константа по её имени.

    Вызывай, когда имя известно точно: «где определён estimate_tokens»,
    «что такое CHUNK_SIZE». Ответ точный — это не поиск по смыслу.

    Args:
        name: Имя функции, класса, метода или константы
    """
    if not name or not name.strip():
        return "Ошибка: пустое имя. Передай в name имя функции, класса или константы."

    project = get_project_map()
    found = project.find(name)

    if not found:
        # Промах по имени чаще всего означает опечатку или пересказ
        # по памяти — покажем ближайшие имена вместо пустого ответа.
        close = difflib.get_close_matches(name.strip(), list(project.symbols), n=5, cutoff=0.7)
        hint = f" Похожие имена в проекте: {', '.join(close)}." if close else ""
        return (
            f"❌ Определения с именем «{name}» в проекте нет.{hint} "
            f"Если имя неточное — попробуй search_code с вопросом своими словами."
        )

    shown = found[:MAX_DEFINITIONS]
    lines = [symbol.render() for symbol in shown]
    if len(found) > len(shown):
        lines.append(f"…и ещё {len(found) - len(shown)} определений с таким именем.")

    return (
        "📍 Определения найдены по таблице символов (разбор кода, не поиск по смыслу). "
        "Адреса точные — называй их как есть.\n\n" + "\n\n".join(lines)
    )


@tool
def list_symbols(where: str) -> str:
    """Перечисляет все функции, классы и константы в файле, модуле или на языке.

    Вызывай на вопросы-перечисления: «какие инструменты в chapter4/src/tools.py»,
    «какие функции есть на typescript», «что внутри модуля memory».
    Это перечисление по разбору, а не поиск по смыслу.

    Args:
        where: Путь к файлу, имя модуля или название языка
    """
    if not where or not where.strip():
        return "Ошибка: пустой аргумент. Передай в where файл, модуль или язык."

    return (
        "📋 Определения по таблице символов (перечисление, не поиск по смыслу):\n\n"
        + get_project_map().list_symbols(where)
    )


@tool
def project_map() -> str:
    """Показывает структуру проекта: папки, точки входа, внешние зависимости.

    Вызывай на вопросы про проект целиком: «из чего состоит проект»,
    «какие зависимости», «откуда запускается».
    """
    return (
        "🗺️ Структура проекта по разбору файлов (не поиск по смыслу):\n\n"
        + get_project_map().overview()
    )


@tool
def dependencies(module: str) -> str:
    """Показывает, что импортирует модуль и кто импортирует его.

    Вызывай на вопросы про связи между частями проекта: «от чего зависит
    knowledge», «кто использует Главу 3».

    Args:
        module: Имя модуля или путь к файлу: knowledge, chapter4/agent.py
    """
    if not module or not module.strip():
        return "Ошибка: пустое имя модуля. Передай в module имя модуля или путь к файлу."

    return (
        "🔗 Импорты по разбору кода (не поиск по смыслу):\n\n"
        + get_project_map().dependencies(module)
    )
