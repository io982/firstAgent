"""
Маршрутизация: кто из специалистов отвечает на эту реплику (пункт 7.5).

Здесь закрывается долг, тянущийся с Главы 5: выбор ветки держится
на списках слов. Списки неполные по построению — «где реализоано
распознование изображений» с двумя опечатками не подошло ни под один
маркер кода и уехало в документы, — и каждая глава честно писала, что
это временно.

Долг закрывается не тем, что списки становятся лучше, а тем, что
появляется ВТОРОЙ способ и возможность их сравнить. Способов два:

  * `route_by_words` — те же предикаты глав 5-6, собранные в одном месте.
    Бесплатно, 0 запросов к модели, полностью предсказуемо;
  * `route_by_model` — один запрос к той же LLM, с `enum` из имён
    специалистов в схеме ответа. Выдумать несуществующего специалиста
    модель не может — грамматика декодирования не разрешит (Глава 2).

Какой из них лучше — вопрос замера, а не вкуса, и замер живёт
в TestRoutingAccuracy. По умолчанию работает бесплатный: платить
за каждую реплику лишним запросом стоит только тогда, когда за это
что-то получаешь.
"""
from __future__ import annotations

import json
import os
import sys
import time
from dataclasses import dataclass

sys.path.append(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

from chapter1.agent import request_model
from chapter5.agent import (
    FILE_MENTION,
    MEMORY_MARKERS,
    SELF_MARKERS,
    looks_like_code_question,
    looks_like_fact_statement,
    looks_like_tool_task,
    matches,
)

from .agents import DEFAULT_SPECIALIST, Team

# Каким маршрутизатором работать: "words" (бесплатно) или "llm" (запрос).
#   PowerShell:   $env:AGENT_ROUTER = "llm"
#   Linux/macOS:  export AGENT_ROUTER=llm
ROUTER = os.environ.get("AGENT_ROUTER", "words")


@dataclass(frozen=True)
class Decision:
    """Решение маршрутизатора вместе с причиной.

    Причина здесь не для красоты: маршрутизация — самое частое место
    ошибки в этом курсе, и «выбрал документы» без «почему» невозможно
    ни отладить, ни измерить. Её печатает REPL и читают тесты.
    """

    agent: str
    why: str = ""
    by: str = "words"

    def render(self) -> str:
        return f"{self.agent} ({self.why})" if self.why else self.agent


# ====================================================================
# МАРШРУТИЗАЦИЯ СЛОВАМИ
