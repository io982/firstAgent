def looks_like_memory_question(text: str) -> bool:
    """Вопрос или утверждение О ПОЛЬЗОВАТЕЛЕ.

    Отличается от augment_with_memory() Главы 5 одним: здесь чистый
    предикат, который не заглядывает в саму память. В Главе 5 ветка
    памяти отключалась, когда фактов ещё не записано, — и вопрос
    «как меня зовут» на пустой памяти уезжал в документы. Для замера
    маршрутизации это негодно: решение о маршруте не должно зависеть
    от того, что уже успели записать.
    """
    lowered = f" {text.lower().strip()} "
    return looks_like_fact_statement(text) or matches(lowered, MEMORY_MARKERS)


# Просьба открыть файл по пути. Список из ОДНОГО глагола, и это не лень:
# «прочитай», «покажи содержимое», «посмотри» уже разбирает Глава 5 своим
# READ_MARKERS, и она это делает лучше — читает файл по карте проекта,
# без вызова инструмента. «Открой» там нет только в паре «открой файл»,
# и живой прогон нашёл дыру ровно в этом месте: «открой ../ROADMAP.md»
# ушло к специалисту по коду, тот подложил фрагменты и сообщил, что файла
# в проекте нет, — вместо того чтобы просто попробовать его прочитать.
OPEN_MARKERS = ("открой", "открыть")

# Вопросы О САМОМ АГЕНТЕ. Список Главы 5 (SELF_MARKERS) узнаёт только те,
# что обращены на «ты»: «какие у ТЕБЯ инструменты», «что ТЫ умеешь».
# Живой прогон показал, что этого мало: «что может агент?» и «что делает
# каждый специалист?» под него не подошли, уехали в документы и получили
# в ответ пересказ Глав 2-3 — текст верный, к вопросу отношения не имеющий.
#
# Маркер-кортеж означает «все основы вместе» (см. matches в Главе 5):
# ("что", "может", "агент") не сработает на «что может пойти не так».
AGENT_MARKERS = (
    ("что", "может", "агент"),
    ("что", "умеет", "агент"),
    ("что", "делает", "агент"),
    ("как", "устроен", "агент"),
    # Основа «специал», а не «специалист»: живой прогон показал вопрос
    # «какие у тебя есть специальности?» — про то же самое, но другим
    # словом, и «специальность» подстроки «специалист» не содержит.
    ("какие", "специал"),
    ("сколько", "специал"),
    ("что", "делает", "специал"),
    ("чем", "занимается", "специал"),
    ("состав", "команд"),
    ("твои", "возможност"),
    # Без «у тебя» тоже: живой прогон показал, что «какие есть инструменты?»
    # спрашивают именно про агента. Вопрос «какие инструменты описаны
    # в главе 2» этот маркер тоже поймает — размен принят сознательно:
    # ошибиться здесь стоит одной справки в контексте вместо другой,
    # а не выдуманного ответа.
    ("какие", "инструмент"),
    ("список", "инструмент"),
    ("кто", "отвечает", "за"),
)


def looks_like_self_question(text: str) -> bool:
    """Вопрос про самого агента — свои маркеры плюс маркеры Главы 5."""
    lowered = f" {text.lower().strip()} "
    return matches(lowered, SELF_MARKERS) or matches(lowered, AGENT_MARKERS)


# Реплика-продолжение: «а память?», «инструменты» — сразу после разговора
# о самом агенте. Своих признаков у неё нет, только короткая длина и то,
# что было перед ней. Приём и число слов — из Главы 5, где так же
# наследуется вид справки о структуре проекта.
#
# Живой прогон, из-за которого это здесь: после «какие у тебя специалисты?»
# реплика «а память?» уехала в документы и получила пересказ Главы 3 про
# три уровня памяти — вместо строчки про специалиста «память», о котором
# и спрашивали.
FOLLOW_UP_WORDS = 5

# Кто отвечал на прошлую реплику. Живёт в модуле, а не в состоянии графа:
# State создаётся заново на каждую реплику, а помнить надо между ними.
# Ограничение отсюда честное — отметка одна на процесс, и на двух
# одновременных разговорах она будет общей.
_last_agent = ""


def remember_route(agent: str) -> None:
    """Запоминает, кто отвечал. Зовёт узел маршрутизации."""
    global _last_agent
    _last_agent = agent


def reset_route_memory() -> None:
    """Забывает прошлый маршрут. Нужна тестам и команде «забудь»."""
    remember_route("")


# Указательные местоимения: слова, которыми реплика ссылается на сказанное
# раньше вместо того, чтобы назвать предмет. Список закрытый — это
# грамматика русского, а не очередной список ключевых слов, который
# придётся дополнять.
REFERENCE_WORDS = (
    "это", "этом", "этого", "этому", "этим", "эта", "эти",
    "том", "тому", "там", "так", "туда", "оттуда",
    "его", "её", "ее", "их", "они", "оно",
)


def continues_previous(text: str, agent: str) -> bool:
    """Реплика-отсылка сразу после ответа этого же специалиста.

    Два условия, и второе важнее первого: реплика короткая И у неё нет
    своего предмета — вместо предмета указательное местоимение. «Где об
    этом говорится?», «а почему так?», «где это описано» — предмет
    остался в предыдущей реплике.

    Нужно это ровно для одного: НЕ ОТКАЗЫВАТЬ по такой реплике. Ворота
    Главы 6 честно видят, что слов «этом» и «говориться» в корпусе нет,
    и отвечают «этого тут нет» — но реплика не про отсутствующую тему,
    она про предыдущую. Живой прогон: «где об этом говориться?» после
    разбора памяти Главы 3 получило отказ, откат к специалисту по коду
    и рассуждение о том, что во фрагментах кода ничего такого нет.

    Проверка на местоимение появилась не сразу, и без неё было хуже,
    чем с отказом: «что такое реранкер?» — тоже три слова, — переставало
    и отказывать, и откатываться. Отказ отключался для всех коротких
    вопросов подряд.
    """
    if not agent or _last_agent != agent:
        return False
    words = text.lower().replace("?", " ").replace(",", " ").split()
    if len(words) > FOLLOW_UP_WORDS:
        return False
    return any(word in REFERENCE_WORDS for word in words)


# Слова, по которым видно, что короткая реплика продолжает разговор
# О САМОМ АГЕНТЕ, а не начинает новый. Имена специалистов сюда попадают
# сами, из состава команды.
FOLLOW_UP_STEMS = ("специал", "инструмент", "умее", "може")


def looks_like_follow_up(text: str, agent: str, team: Team | None = None) -> bool:
    """Короткая реплика, продолжающая разговор с этим же специалистом.

    Одной длины НЕ ХВАТАЕТ, и это выяснилось живым прогоном. Первая
    версия считала продолжением любую короткую реплику после «о себе» —
    и разговор в «о себе» залипал навсегда: «о чем курс?», «какие модели
    использованы в курсе?», «## Целевое железо» уходили туда же, потому
    что каждая короткая реплика заново подтверждала отметку. Вопросы
    к документам после первого же вопроса о себе переставали работать.

    Поэтому признак опирается на СОДЕРЖАНИЕ: реплика должна называть
    то, о чём шла речь, — имя специалиста («а память?», «инструменты»)
    или слово про состав. «О чём курс?» ни одного такого слова
    не содержит и уезжает в документы, как и должно.
    """
    if not agent or _last_agent != agent:
        return False
    if len(text.split()) > FOLLOW_UP_WORDS:
        return False

    lowered = text.lower()
    names = (team or Team()).names()
    return any(name in lowered for name in names) or any(
        stem in lowered for stem in FOLLOW_UP_STEMS
    )


def looks_like_file_task(text: str) -> bool:
    """Просьба открыть файл, названный путём.

    Оба признака обязательны. Без имени файла «открой» — это что угодно
    («открой доступ», «открой список»), а без глагола имя файла означает
    вопрос про код, а не просьбу его показать.
    """
    lowered = f" {text.lower().strip()} "
    return bool(matches(lowered, OPEN_MARKERS) and FILE_MENTION.search(text))


def route_by_words(text: str, team: Team | None = None) -> Decision:
    """Маршрут по спискам слов — ровно порядок route() Главы 6.

    Порядок проверок значим и разобран в главах 5-6:

      1. задача для инструмента («сколько будет 2+2», «погода») — там
         вообще нечего искать, и поиск только мешает;
      2. реплика о пользователе — иначе «меня зовут io982» уходит
         в поиск по коду и получает список классов проекта;
      3. вопрос про код — по словам, по имени файла и по имени
         из карты проекта;
      4. всё остальное — документы.
    """
    team = team or Team()

    # Вопрос о самом агенте проверяется ПЕРВЫМ: он самый узкий. «Какие
    # у тебя инструменты» подходит и под маркеры кода тоже, а отвечать
    # на него надо реестром, а не поиском по проекту.
    if looks_like_self_question(text) and "о себе" in team.members:
        return Decision("о себе", "вопрос про самого агента", "words")
    if looks_like_tool_task(text) or looks_like_file_task(text):
        return Decision("инструменты", "похоже на задачу для инструмента", "words")
    if looks_like_memory_question(text):
        return Decision("память", "реплика о пользователе", "words")
    if looks_like_code_question(text):
        return Decision("код", "слова или имена из проекта", "words")

    # Проверяется ПОСЛЕДНЕЙ, вместо корпуса по умолчанию, а не первой.
    # Порядок тут решает всё: «как меня зовут?» — тоже короткая реплика,
    # и проверь мы продолжение раньше, вопрос о пользователе уехал бы
    # к тому, кто отвечал в прошлый раз.
    if looks_like_follow_up(text, "о себе", team) and "о себе" in team.members:
        return Decision("о себе", "короткое продолжение разговора о самом агенте", "words")

    return Decision(team.default, "ничего не сработало — корпус по умолчанию", "words")


