"""
Специалисты: агент — это не реестр инструментов, а выборка из него.

Мысль, ради которой написана глава, целиком помещается в одну строчку
кода: `build_system_prompt(only=[...])`. Всё остальное — следствия.

До этой главы агент был один и видел весь реестр: 16 инструментов
и правила всех глав сразу. Замер Главы 4 показал, чем за это заплачено, —
получив пачку документов, `qwen2.5:3b` переставала видеть инструменты
памяти и на «меня зовут io982» отвечала «в базе знаний нет информации
о том, что вас так зовут». Промптом это не лечилось: пробовали и отдельное
правило, и напоминание в конце контекста.

Здесь из того же реестра собираются пять агентов. Новых инструментов
не добавлено НИ ОДНОГО — это и есть суть: специализация не про то, чтобы
дописать функций, а про то, чтобы каждому дать меньше. Пятому, «о себе»,
не досталось вообще ни одного, и он при этом полноценный специалист.

Что получает специалист:

  * своё имя и роль (роль читает маршрутизатор — см. router.py);
  * свой набор инструментов — и `enum` в схеме ответа собран по нему,
    так что позвать чужой инструмент специалист не может физически;
  * свои правила — только те, что относятся к его работе;
  * свой поиск — функция, которую приносит декоратор `@specialist`;
  * свой контекст — отдельный диалог на каждого (см. chapter7/agent.py).

⚠️ В этом файле лежит РЕЕСТР, а не сами специалисты. Устроено как реестр
инструментов Главы 2: пока никто не импортировал chapter7/agent.py, где
специалисты объявлены декоратором, SPECIALISTS пуст, и `Team()` соберётся
пустой. Порядок импортов значим — как во всех главах начиная с третьей.
"""
